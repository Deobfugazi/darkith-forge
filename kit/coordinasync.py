def _root():
    """The project this bundle is deployed INTO.

    Default is the directory holding this file, not the process cwd: the kit is carried as one
    file and dropped into a project root, so "beside me" is the only location it can trust. The
    cwd default made a copy in /tmp operate on /tmp itself, one level above the project it had
    just installed into.
    """
    explicit = os.environ.get("COORDINASYNC_ROOT")
    if explicit:
        return os.path.abspath(explicit)
    # A project marker in the working directory wins: someone who runs
    # `python3 kit/coordinasync.py check` from their project root means THAT project, not the
    # subdirectory the bundle happens to live in. With no marker the bundle's own directory is
    # the only thing that can be trusted — that is the copy-dropped-somewhere case, and it must
    # never reach upward to whatever project happens to sit above it.
    cwd = os.getcwd()
    if os.path.isfile(os.path.join(cwd, "TASKS.md")) or             os.path.isfile(os.path.join(cwd, ".coordinasync.json")):
        return cwd
    return os.path.dirname(os.path.abspath(__file__))


def _call(name, argv):
    """Run an embedded tool's main() with argv, restoring sys.argv afterwards.

    The tools parse sys.argv themselves (argparse), so a caller passing a list would be
    silently ignored; setting sys.argv is the contract they actually honour.
    """
    mod = sys.modules[name]
    saved = sys.argv
    saved_root = os.environ.get("COORDINASYNC_ROOT")
    # An embedded module's __file__ is THIS file, so its own parent.parent is not the project.
    # The caller knows the project root; hand it over explicitly or the tools operate on /tmp.
    if not os.environ.get("COORDINASYNC_ROOT"):
        os.environ["COORDINASYNC_ROOT"] = _root()
    sys.argv = [name + ".py"] + list(argv)
    try:
        return mod.main()
    finally:
        sys.argv = saved
        if saved_root is None:
            os.environ.pop("COORDINASYNC_ROOT", None)
        else:
            os.environ["COORDINASYNC_ROOT"] = saved_root


def selftest():
    """Prove the whole chain in a throwaway repo. Never touches the tree beside this file."""
    import json
    import tempfile

    checks = []
    with tempfile.TemporaryDirectory() as td:
        root = os.path.join(td, "host")
        os.makedirs(os.path.join(root, "proof"))
        with open(os.path.join(root, "TASKS.md"), "w") as f:
            f.write(SEED_BOARD)
        ev = os.path.join(td, "conversations", "fake-session", "events")
        os.makedirs(ev)
        with open(os.path.join(ev, "event-00001-aaaa.json"), "w") as f:
            f.write('{"kind":"MessageEvent","timestamp":"2020-01-01T00:00:00.000000",'
                    '"llm_message":{"role":"user","content":[{"type":"text",'
                    '"text":"add the gatekeeper and propagate it to every board"}]}}')

        old_root = os.environ.get("COORDINASYNC_ROOT")
        old_ev = os.environ.get("COORDINASYNC_EVENT_ROOTS")
        os.environ["COORDINASYNC_ROOT"] = root
        os.environ["COORDINASYNC_EVENT_ROOTS"] = os.path.join(td, "conversations")
        try:
            _load()
            gate = sys.modules["chat_gatekeeper"]
            praxis = sys.modules["praxis_propagate"]
            pulse = sys.modules["synchrony_pulse"]

            rc = _call("chat_gatekeeper", ["--write"])
            board = open(os.path.join(root, "TASKS.md")).read()
            checks.append(("ingest wrote an order", rc == 0 and "gatekeeper" in board))
            checks.append(("order is on the board", "**[order]**" in board))
            checks.append(("coupled laws declared", "**Coupled laws:**" in board))
            checks.append(("check passes after write", _call("chat_gatekeeper", ["--check"]) == 0))
            checks.append(("guard selftest passes", _call("chat_gatekeeper", ["--selftest"]) == 0))
            checks.append(("propagator selftest passes", _call("praxis_propagate", ["--selftest"]) == 0))
            checks.append(("propagation runs", _call("praxis_propagate", []) == 0))
            checks.append(("propagated block present",
                           "PRAXIS:BEGIN" in open(os.path.join(root, "TASKS.md")).read()))
            checks.append(("pulse runs", _call("synchrony_pulse", []) == 0))
            pj = os.path.join(root, "proof", "synchrony_pulse.json")
            has_pulse = os.path.isfile(pj)
            checks.append(("pulse written", has_pulse))
            if has_pulse:
                d = json.load(open(pj))
                checks.append(("pulse is boot-aware", "boot" in d and "currentPhase" in d))
            def block():
                txt = open(os.path.join(root, "TASKS.md")).read()
                return txt.split("CHAT-GATE:BEGIN", 1)[1].split("CHAT-GATE:END", 1)[0]

            # Compare the region the ingester OWNS. praxis rewrites its own block in the same
            # file, so hashing the whole board would measure praxis's work as ingest drift.
            before = block()
            _call("chat_gatekeeper", ["--write"])
            checks.append(("re-ingest is idempotent", block() == before))
        finally:
            if old_root is None:
                os.environ.pop("COORDINASYNC_ROOT", None)
            else:
                os.environ["COORDINASYNC_ROOT"] = old_root
            if old_ev is None:
                os.environ.pop("COORDINASYNC_EVENT_ROOTS", None)
            else:
                os.environ["COORDINASYNC_EVENT_ROOTS"] = old_ev

    ok = True
    for name, cond in checks:
        print(("  ok   " if cond else "  FAIL ") + name)
        ok = ok and bool(cond)
    print("coordinasync selftest: %s — %d/%d" % ("ok" if ok else "BROKEN", sum(
        1 for _, c in checks if c), len(checks)))
    return 0 if ok else 1


def install():
    root = _root()
    os.makedirs(os.path.join(root, "proof"), exist_ok=True)
    tools = os.path.join(root, "tools")
    os.makedirs(tools, exist_ok=True)
    board = os.path.join(root, "TASKS.md")
    if not os.path.isfile(board):
        open(board, "w").write(SEED_BOARD)
        print("  seeded TASKS.md")
    for name in ("chat_gatekeeper", "praxis_propagate", "synchrony_pulse", "law_gate"):
        dst = os.path.join(tools, name + ".py")
        open(dst, "w").write(zlib.decompress(base64.b64decode(_MODULES[name])).decode())
        print("  installed tools/%s.py" % name)
    gen = os.path.join(root, "build", "gen")
    os.makedirs(gen, exist_ok=True)
    open(os.path.join(gen, "omega_time_runtime.py"), "w").write(
        zlib.decompress(base64.b64decode(_MODULES["omega_time_runtime"])).decode())
    print("  installed build/gen/omega_time_runtime.py")
    print("  next: python3 tools/chat_gatekeeper.py --write")
    return 0


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    cmd = argv[0] if argv else "selftest"
    rest = argv[1:]
    if cmd == "selftest":
        return selftest()
    if cmd == "install":
        return install()
    if cmd in ("ingest", "board", "pulse", "check"):
        _load()
        if cmd == "pulse":
            return _call("synchrony_pulse", rest)
        if cmd == "check":
            rc = _call("chat_gatekeeper", ["--check"])
            rc |= _call("praxis_propagate", ["--check"])
            return rc
        if cmd == "ingest":
            rc = _call("chat_gatekeeper", ["--write"])
            if rc == 0:
                _call("praxis_propagate", [])
                print("  every board carried by this project is pinged")
            return rc
        board = os.path.join(_root(), "TASKS.md")
        if not os.path.isfile(board):
            print("coordinasync: no TASKS.md at " + _root())
            return 1
        text = open(board).read()
        print(text.split("CHAT-GATE:BEGIN", 1)[1].split("CHAT-GATE:END", 1)[0]
              if "CHAT-GATE:BEGIN" in text else text[:2000])
        return 0
    print(__doc__)
    return 0


