def _load():
    # Modules compute ROOT at exec time from COORDINASYNC_ROOT, so it must be set BEFORE the
    # first load. Setting it only in _call() was too late: ROOT was already baked to the
    # single file's grandparent directory and every tool operated one level above the project.
    if not os.environ.get("COORDINASYNC_ROOT"):
        os.environ["COORDINASYNC_ROOT"] = _root()
    for name, blob in _MODULES.items():
        mod = types.ModuleType(name)
        mod.__file__ = __file__
        sys.modules[name] = mod
        exec(compile(zlib.decompress(base64.b64decode(blob)).decode(), name + ".py", "exec"),
             mod.__dict__)


