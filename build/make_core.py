#!/usr/bin/env python3
"""Extract the SAVF truth-function core from savf.html.

SAVF is not an application.  It is one truth function: a DOM-free engine that
maps source bytes to a verdict over gates phi0..phi10.  Every surface that
consumes it -- the standalone page (savf.html), the code manager, the forge and
the terminal -- must run the *same* engine, or the verdicts diverge and the
truth function stops being one function.

This script pulls the engine half of savf.html (everything before app/ui.js)
plus the reference tables (stdlib/stdlib-attributes) that the scanner needs, and
writes build/savf-core.js: a single self-contained module with no DOM access.

Run:  python3 build/make_core.py
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SAVF_HTML = ROOT / "savf.html"
FACADE = ROOT / "build" / "truth-facade.js"
OUT = ROOT / "build" / "savf-core.js"

ENGINE_MARK = "/* ==================== app/ui.js"
REFS_MARK = "/* ==================== reference tables"

BANNER = """/* ============================================================================
   SAVF truth-function core  --  generated by build/make_core.py
   Do not edit by hand; edit savf.html and re-run the pipeline.

   DOM-free.  Exposes, on the global object:
     PyLex  PyAst  SavfScan  SavfHash  SavfCore  SavfAudit
     SAVF_STDLIB  SAVF_STDATTRIB
   plus the unified facade `SAVF` (see build/truth-facade.js, appended by the
   pipeline) so any host -- page, code manager, forge or terminal -- gets one
   identical verdict for one identical input.
   ============================================================================ */
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify generated core; write nothing")
    args = ap.parse_args()

    html = SAVF_HTML.read_text(encoding="utf-8")
    m = re.search(r"<script[^>]*>([\s\S]*?)</script>", html)
    if not m:
        print("savf.html: no <script> block found", file=sys.stderr)
        return 1
    js = m.group(1)

    ui = js.find(ENGINE_MARK)
    refs = js.find(REFS_MARK)
    if ui < 0 or refs < 0:
        print("savf.html: engine or reference marker missing", file=sys.stderr)
        return 1

    engine = js[:ui]
    tables = js[refs:]

    # The page publishes its reference tables as `window.SAVF_*`.  The core is
    # documented as host-agnostic, so bind `window` to the real global first;
    # otherwise the core loads only in a browser and throws under Node or any
    # other host that has no `window`.  In a browser this is a no-op.
    shim = ("/* Host shim: the reference tables below are written as `window.SAVF_*`.\n"
            "   Make `window` name the real global so the core also loads outside\n"
            "   a browser (Node, worker, any DOM-free host). */\n"
            'var window = (typeof window !== "undefined") ? window : globalThis;\n\n')

    # The engine is DOM-free by construction; assert it, because a stray
    # document lookup would break the terminal and forge hosts silently.
    for needle in ("document.", "getElementById"):
        if needle in engine or needle in tables:
            print(f"savf.html: core unexpectedly references {needle!r}", file=sys.stderr)
            return 1

    core = BANNER + shim + engine.rstrip() + "\n\n" + tables.rstrip() + "\n\n"
    core += FACADE.read_text(encoding="utf-8").rstrip() + "\n"
    have = {name: (f"global.{name}" in core) for name in
            ("PyLex", "PyAst", "SavfScan", "SavfHash", "SavfCore", "SavfAudit")}
    print("  modules: " + " ".join(f"{k}={'ok' if v else 'MISSING'}" for k, v in have.items()))
    print(f"  tables:  STDLIB={'ok' if 'global.SAVF_STDLIB' in core else 'MISSING'} "
          f"STDATTRIB={'ok' if 'global.SAVF_STDATTRIB' in core else 'MISSING'}")
    print(f"  facade:  auditSource={'ok' if 'auditSource' in core else 'MISSING'} "
          f"auditFiles={'ok' if 'auditFiles' in core else 'MISSING'}")
    if not all(have.values()):
        return 1
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != core:
            print(f"OUT OF SYNC: {OUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print("check: in sync (write-free)")
        return 0
    OUT.write_text(core, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}  {len(core)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
