#!/usr/bin/env python3
"""gen_synchrony.py — the ONE generator for the synchrony timestamp runtime (MUST #23/#24).

Prime bylaw: synchrony IS time tracking. Every app and every bot carries timestamp
awareness, and that code is GENERATED here, never hand-written per app (MUST #17).

Emits two byte-identical-for-identical-inputs artifacts:
  build/gen/omega_time.js           the browser runtime injected into every app HTML surface
  build/gen/omega_time_runtime.py   the bot runtime imported by every automation

The zone is the Operator's (Asia/Manila, UTC+8), matching tools/omega_time.py, so a
timestamp taken in an app, a bot, or the CLI sorts against the others diachronically.

Run:  python3 build/gen_synchrony.py
"""
import hashlib
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "build/gen"

JS = r"""/* omega-time — GENERATED by build/gen_synchrony.py. DO NOT HAND-EDIT.
   Synchrony bylaw: every surface carries timestamp awareness so documents, logs and
   artifacts sort diachronically. Operator zone: Asia/Manila (UTC+8). */
(function () {
  "use strict";
  var TZ_HOURS = 8, TZ_NAME = "Asia/Manila (UTC+8)";
  function pad(n) { return (n < 10 ? "0" : "") + n; }
  function local(d) { return new Date((d || new Date()).getTime() + (TZ_HOURS * 60 + (d || new Date()).getTimezoneOffset()) * 60000); }
  function parts(d) { var t = local(d); return { y: t.getFullYear(), mo: t.getMonth() + 1, da: t.getDate(), h: t.getHours(), mi: t.getMinutes(), s: t.getSeconds() }; }
  var omegaTime = {
    tz: TZ_NAME,
    now: function () { return new Date(); },
    parts: parts,
    /* "YYYY-MM-DD HH:MM:SS" — human, Operator-local */
    stamp: function (d) { var p = parts(d); return p.y + "-" + pad(p.mo) + "-" + pad(p.da) + " " + pad(p.h) + ":" + pad(p.mi) + ":" + pad(p.s); },
    /* "YYYY-MM-DDTHH:MM:SS+08:00" — lexicographically sortable (diachronic sort key) */
    iso: function (d) { var p = parts(d); return p.y + "-" + pad(p.mo) + "-" + pad(p.da) + "T" + pad(p.h) + ":" + pad(p.mi) + ":" + pad(p.s) + "+08:00"; },
    key: function (d) { return this.iso(d); },
    label: function (d) { return this.stamp(d) + " \u00b7 " + this.tz; },
    /* diachronic sort: oldest first by default; pass true for newest first */
    sortBy: function (items, getKey, newestFirst) {
      return items.slice().sort(function (a, b) {
        var ka = getKey(a), kb = getKey(b);
        return newestFirst ? (ka < kb ? 1 : ka > kb ? -1 : 0) : (ka < kb ? -1 : ka > kb ? 1 : 0);
      });
    }
  };
  if (typeof window !== "undefined") { window.omegaTime = omegaTime; }
  if (typeof module !== "undefined" && module.exports) { module.exports = omegaTime; }
})();
"""

PY = r'''"""omega_time_runtime — GENERATED by build/gen_synchrony.py. DO NOT HAND-EDIT.

Synchrony bylaw: every bot logs with a timestamp so its output sorts diachronically
against every app's. Operator zone: Asia/Manila (UTC+8). Mirrors build/gen/omega_time.js.
"""
import sys
from datetime import datetime, timedelta, timezone

TZ = timezone(timedelta(hours=8))
TZ_NAME = "Asia/Manila (UTC+8)"


def stamp(dt=None):
    """'YYYY-MM-DD HH:MM:SS' — human, Operator-local."""
    return (dt or datetime.now(TZ)).astimezone(TZ).strftime("%Y-%m-%d %H:%M:%S")


def iso(dt=None):
    """'YYYY-MM-DDTHH:MM:SS+08:00' — lexicographically sortable (diachronic sort key)."""
    return (dt or datetime.now(TZ)).astimezone(TZ).isoformat(timespec="seconds")


def log(msg, stream=None):
    """Timestamped log line: '[YYYY-MM-DD HH:MM:SS] msg'. Every bot routes output here."""
    line = "[%s] %s" % (stamp(), msg)
    print(line, file=stream or sys.stdout)
    return line


def sort_by(items, get_key, newest_first=False):
    """Diachronic sort by an ISO key extracted from each item."""
    return sorted(items, key=get_key, reverse=newest_first)
'''


def write(path: pathlib.Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main() -> int:
    jh = write(OUT / "omega_time.js", JS)
    ph = write(OUT / "omega_time_runtime.py", PY)
    print(f"gen_synchrony: wrote build/gen/omega_time.js  sha256 {jh[:16]}")
    print(f"gen_synchrony: wrote build/gen/omega_time_runtime.py  sha256 {ph[:16]}")
    print(f"gen_synchrony: zone Asia/Manila (UTC+8) — one clock for apps, bots and CLI")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
