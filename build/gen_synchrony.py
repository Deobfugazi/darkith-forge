import os
import sys
from datetime import datetime, timedelta, timezone

TZ = timezone(timedelta(hours=8))
TZ_NAME = "Asia/Manila (UTC+8)"
# the Operator's default cycle: wake/activity vs rest/digest/restore (deactivity)
CYCLE = {"activeStart": 6, "activeEnd": 22}


def _as_dt(dt):
    """Coerce None | datetime | ISO string to an aware Operator-local datetime.

    Every public function accepts all three, so a stamp() string round-trips without a
    naive/aware crash (the defect that made an activity gap uncomputable).
    """
    if dt is None:
        return datetime.now(TZ)
    if isinstance(dt, str):
        dt = datetime.fromisoformat(dt)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=TZ)
    return dt.astimezone(TZ)


def stamp(dt=None):
    """'YYYY-MM-DD HH:MM:SS' — human, Operator-local."""
    return _as_dt(dt).strftime("%Y-%m-%d %H:%M:%S")


def iso(dt=None):
    """'YYYY-MM-DDTHH:MM:SS+08:00' — lexicographically sortable (diachronic sort key)."""
    return _as_dt(dt).isoformat(timespec="seconds")


def log(msg, stream=None):
    """Timestamped log line: '[YYYY-MM-DD HH:MM:SS] msg'. Every bot routes output here."""
    line = "[%s] %s" % (stamp(), msg)
    print(line, file=stream or sys.stdout)
    return line


def sort_by(items, get_key, newest_first=False):
    """Diachronic sort by an ISO key extracted from each item."""
    return sorted(items, key=get_key, reverse=newest_first)


def device_relation(dt=None):
    """Autocouple the edge device's own system local time to the global clock.

    Returns the device's local time, its UTC offset, the global epoch, and whether the
    device's own zone agrees with the Operator's. A device set to the wrong zone shows
    agrees=False — the drift the Operator must see (SPI-2: read the real bytes).
    """
    now = dt or datetime.now()
    off = now.astimezone().utcoffset() or timedelta(0)
    off_min = int(off.total_seconds() // 60)
    return {
        "deviceLocal": now.strftime("%Y-%m-%d %H:%M:%S"),
        "deviceOffsetMin": off_min,
        "deviceZone": "UTC%+03d:%02d" % (off_min // 60, abs(off_min) % 60),
        "globalUtc": now.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "globalEpochMs": int(now.timestamp() * 1000),
        "agrees": off_min == 8 * 60,
    }


def phase(dt=None):
    """The Operator's cycle phase for an instant: wake/active or rest/digest/restore."""
    h = _as_dt(dt).hour
    return "wake/active" if CYCLE["activeStart"] <= h < CYCLE["activeEnd"] else "rest/digest/restore"


def since(prior, dt=None):
    """Hours since a prior instant (e.g. the last conversation activity).

    Accepts a datetime or an ISO string. A naive value is read as Operator-local, so a
    string written by stamp() compares correctly against now (never a naive/aware crash).
    """
    return (_as_dt(dt) - _as_dt(prior)).total_seconds() / 3600.0


def classify(dt=None):
    """An instant classified by stamp and cycle phase."""
    return {"stamp": stamp(dt), "phase": phase(dt), "active": phase(dt) == "wake/active"}


def boot_stamp():
    """The boot instant of this process, Operator-local — for boot-aware sessions.

    A session that knows when it booted can place its own activity on the Operator's
    timeline, which is what makes the board's 'last activity' meaningful.
    """
    return stamp(datetime.now(TZ) - timedelta(seconds=_uptime_seconds()))


def _uptime_seconds():
    try:
        with open("/proc/uptime", "r", encoding="utf-8") as fh:
            return float(fh.read().split()[0])
    except (OSError, ValueError, IndexError):
        return 0.0
