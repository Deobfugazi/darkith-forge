def main() -> int:
    parts = [HEAD]
    for name, path in MODULES.items():
        src = path.read_text()
        blob = base64.b64encode(zlib.compress(src.encode(), 9)).decode()
        wrapped = "\n".join('    "%s"' % ln for ln in textwrap.wrap(blob, 96))
        parts.append('_MODULES["%s"] = (\n%s\n)\n' % (name, wrapped))
    parts.append(TAIL)
    text = "".join(parts)
    compile(text, "coordinasync.py", "exec")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    OUT.chmod(0o755)
    print("  wrote %s (%d B, %d module(s) embedded)" % (
        OUT.relative_to(ROOT), len(text), len(MODULES)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
