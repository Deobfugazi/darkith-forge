#!/usr/bin/env python3
"""make-coordinasync.py — emit ONE self-contained Python file carrying the toolkit.

The Operator hops between cloud accounts. A toolkit that needs a directory tree, a venv, an
installer, or a package index does not survive the hop; a single .py that runs on a stock
python3 does. So the toolkit ships as one file with its modules embedded, compressed, and
loaded straight into sys.modules — no temp extraction, no archive, no dependencies.

  python3 build/make-coordinasync.py            -> kit/coordinasync.py
"""
import base64
import pathlib
import textwrap
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
# Committed, not built-and-forgotten: dist/ is gitignored, so an artifact there would
# not travel with the source tree at all. The kit lives in kit/ and is tracked.
OUT = ROOT / "kit" / "coordinasync.py"
# Read the ONE copy of each module. The kit is a BUILT ARTIFACT, not a second tree: keeping
# kit/tools as a copy of tools/ made two tracked paths with divergent bytes, which is precisely
# the fork NEVER #11 forbids. The bundle is generated from tools/ and carries the bytes; the
# sources stay single.
MODULES = {
    "omega_time_runtime": ROOT / "build/gen/omega_time_runtime.py",
    "chat_gatekeeper": ROOT / "tools/chat_gatekeeper.py",
    "praxis_propagate": ROOT / "tools/praxis_propagate.py",
    "synchrony_pulse": ROOT / "tools/synchrony_pulse.py",
    # praxis reuses law_gate's regex deliberately (SPI-27: one lexer, one examiner). Forking it
    # would create the second definition the law forbids, so the module travels inside the bundle.
    "law_gate": ROOT / "tools/law_gate.py",
}

