#!/usr/bin/env python3
"""omega_deficit.py — the NT XI progress-deficit indicator, computed from the durable board.

NT XI (Autophagic Sovereign Economy) carries the retention law:

    W_in - E = S != 0,   absolution as E/W_in -> 0

where W_in is the wealth generated by labor/care/resources, E is extraction (value that
leaves the system without returning to the source), and S is the surplus that must circulate.
The M6 SE predicate (five clauses) is the per-exchange non-extraction check: clause 2/3 say the
retention ratio must not increase (non-extractive for A and for B), clause 5 says the engine
retains no state across a call.

This tool reads that law off the two durable records and computes the project's own deficit:

  W_in = all named work   = TASKS.md rows + DEFICITS.json entries
  E    = un-returned work  = board (todo + in_progress + blocked) + deficits (open)
  S    = returned work     = board done + deficits (closed + descoped)
  ratio = E / W_in         = the progress-deficit indicator; absolution at 0

The ratio IS the distance from omega. A rising ratio across a delivery is extraction; it fails
unless the deficit ledger gained a formal `descoped` entry (M6 non-extractive, NEVER #17).

The computed indicator is written to the board (TASKS.md §H) and to proof/omega_deficit.json.
This tool is fail-closed: it fails if the records are missing/malformed, if the board's printed
indicator is stale, or if the ratio rose across a delivery without a descope.

Usage:
  python3 tools/omega_deficit.py            # check: board + proof must match the computation
  python3 tools/omega_deficit.py --write    # recompute and write TASKS.md §H + proof/omega_deficit.json
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BOARD = ROOT / "TASKS.md"
LEDGER = ROOT / "DEFICITS.json"
PROOF = ROOT / "proof" / "omega_deficit.json"
MANIFEST = ROOT / "app/src/main/AndroidManifest.xml"

STATUSES = {"done", "todo", "in_progress", "blocked"}
RETURNED = {"done"}
OPEN_STATUSES = {"todo", "in_progress", "blocked"}

LAW = "NT XI: W_in - E = S != 0; absolution as E/W_in -> 0"
SECTION_HEAD = "## H. NT XI"


def board_rows() -> list[tuple[int, str, str]]:
    """(lineno, task, status) for work rows; generated stage telemetry is not work."""
    rows = []
    in_revitalization = False
    for i, line in enumerate(BOARD.read_text(encoding="utf-8").splitlines(), 1):
        if line.strip().startswith("<!-- REVITALIZATION:BEGIN"):
            in_revitalization = True
            continue
        if line.strip().startswith("<!-- REVITALIZATION:END"):
            in_revitalization = False
            continue
        if in_revitalization:
            continue
        if not line.lstrip().startswith("|") or set(line) <= set("|-: "):
            continue
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) >= 4 and c[2] in STATUSES:
            rows.append((i, c[1], c[2]))
    return rows


def versioncode() -> int | None:
    if not MANIFEST.is_file():
        return None
    m = re.search(r'android:versionCode="(\d+)"', MANIFEST.read_text(encoding="utf-8"))
    return int(m.group(1)) if m else None


def compute() -> dict:
    if not BOARD.is_file():
        raise SystemExit("omega_deficit: FAIL - no TASKS.md (the durable board is missing)")
    if not LEDGER.is_file():
        raise SystemExit("omega_deficit: FAIL - no DEFICITS.json (the deficit ledger is missing)")

    rows = board_rows()
    board = {s: 0 for s in STATUSES}
    for _, _, s in rows:
        board[s] += 1
    board_total = sum(board.values())

    led = json.loads(LEDGER.read_text(encoding="utf-8"))
    entries = led.get("deficits", [])
    defc = {"closed": 0, "descoped": 0, "open": 0}
    for e in entries:
        st = e.get("status")
        if st not in defc:
            raise SystemExit(f"omega_deficit: FAIL - deficit {e.get('id')!r} has status {st!r}")
        defc[st] += 1
    deficit_total = len(entries)

    W_in = board_total + deficit_total
    E = sum(board[s] for s in OPEN_STATUSES) + defc["open"]
    S = board["done"] + defc["closed"] + defc["descoped"]
    if W_in != E + S:
        raise SystemExit(f"omega_deficit: FAIL - W_in({W_in}) != E({E}) + S({S}) (ledger does not balance)")
    ratio = (E / W_in) if W_in else 0.0

    return {
        "law": LAW,
        "delivery_versioncode": versioncode(),
        "W_in": W_in,
        "E": E,
        "S": S,
        "ratio": round(ratio, 4),
        "absolution": E == 0,
        "omega": E == 0,
        "components": {
            "board_total": board_total,
            "board_done": board["done"],
            "board_todo": board["todo"],
            "board_in_progress": board["in_progress"],
            "board_blocked": board["blocked"],
            "deficit_total": deficit_total,
            "deficits_closed": defc["closed"],
            "deficits_descoped": defc["descoped"],
            "deficits_open": defc["open"],
        },
    }


def render_section(d: dict) -> str:
    c = d["components"]
    return "\n".join([
        f"{SECTION_HEAD} - THE OMEGA PROGRESS-DEFICIT INDICATOR",
        "",
        "NT XI (Autophagic Sovereign Economy) carries the retention law `W_in - E = S != 0`, with",
        "absolution as `E/W_in -> 0`. Read off the durable board and the deficit ledger, it is this",
        "project's own progress-deficit indicator. `W_in` is all named work; `E` is work named but not",
        "returned to the source; `S` is work returned. A rising ratio across a delivery is extraction",
        "and fails CI (M6 SE non-extractive clause / NEVER #17) unless a deficit is formally descoped.",
        "",
        "| metric | value | meaning |",
        "|---|---|---|",
        f"| W_in | {d['W_in']} | named work = board {c['board_total']} + deficits {c['deficit_total']} |",
        f"| E | {d['E']} | un-returned = todo {c['board_todo']} + in_progress {c['board_in_progress']} + blocked {c['board_blocked']} + open {c['deficits_open']} |",
        f"| S | {d['S']} | returned = done {c['board_done']} + closed {c['deficits_closed']} + descoped {c['deficits_descoped']} |",
        f"| E/W_in | {d['ratio']:.3f} | the progress-deficit indicator; absolution at 0 |",
        f"| absolution | {'YES' if d['absolution'] else 'NO'} | E = 0 (all named work returned) |",
        "",
        "Computed and gated by `tools/omega_deficit.py`; recorded at `proof/omega_deficit.json`.",
    ])


def write_all(d: dict) -> None:
    text = BOARD.read_text(encoding="utf-8")
    section = render_section(d)
    # replace an existing §H section, or append one before the final divider/trailer.
    if SECTION_HEAD in text:
        head = text.index(SECTION_HEAD)
        # find the start of the next top-level '## ' section after §H
        nxt = text.find("\n## ", head + 1)
        text = text[:head] + section + ("\n" + text[nxt:] if nxt != -1 else "\n")
    else:
        text = text.rstrip() + "\n\n" + section + "\n"
    BOARD.write_text(text, encoding="utf-8")

    PROOF.parent.mkdir(parents=True, exist_ok=True)
    hist = []
    if PROOF.is_file():
        try:
            hist = json.loads(PROOF.read_text(encoding="utf-8")).get("history", [])
        except json.JSONDecodeError:
            hist = []
    vc = d["delivery_versioncode"]
    rec = {"delivery_versioncode": vc, "W_in": d["W_in"], "E": d["E"],
           "ratio": d["ratio"], "deficits_descoped": d["components"]["deficits_descoped"]}
    if not any(h.get("delivery_versioncode") == vc for h in hist):
        hist.append(rec)
    else:
        hist = [rec if h.get("delivery_versioncode") == vc else h for h in hist]
    hist.sort(key=lambda h: h.get("delivery_versioncode") or 0)
    d["history"] = hist
    PROOF.write_text(json.dumps(d, indent=2) + "\n", encoding="utf-8")


def check(d: dict) -> int:
    text = BOARD.read_text(encoding="utf-8")
    if SECTION_HEAD not in text:
        print("omega_deficit: FAIL - TASKS.md has no §H indicator (run: --write)")
        return 1
    if f"| E/W_in | {d['ratio']:.3f} |" not in text:
        print(f"omega_deficit: FAIL - TASKS.md §H indicator is stale (expected E/W_in = {d['ratio']:.3f}; run: --write)")
        return 1
    if not PROOF.is_file():
        print("omega_deficit: FAIL - proof/omega_deficit.json is missing (run: --write)")
        return 1
    proof = json.loads(PROOF.read_text(encoding="utf-8"))
    if (proof.get("W_in"), proof.get("E"), proof.get("ratio")) != (d["W_in"], d["E"], d["ratio"]):
        print(f"omega_deficit: FAIL - proof/omega_deficit.json is stale "
              f"(proof E/W_in={proof.get('E')}/{proof.get('W_in')}, computed {d['E']}/{d['W_in']}; run: --write)")
        return 1

    # M6 SE non-extractive: the ratio must not rise across a delivery unless THAT delivery
    # formally descoped a deficit (a new descope, not a historical one).
    vc = d["delivery_versioncode"]
    hist = proof.get("history", [])
    prev = [h for h in hist if h.get("delivery_versioncode") != vc]
    cur_descoped = next((h.get("deficits_descoped") for h in hist
                         if h.get("delivery_versioncode") == vc), None)
    if cur_descoped is None:
        cur_descoped = d["components"]["deficits_descoped"]
    if prev:
        last = max(prev, key=lambda h: h.get("delivery_versioncode") or 0)
        if d["ratio"] > last.get("ratio", 0.0) and cur_descoped <= last.get("deficits_descoped", 0):
            print(f"omega_deficit: FAIL - the ratio rose across a delivery "
                  f"({last.get('ratio')} -> {d['ratio']}) with no NEW descope "
                  f"(descoped {last.get('deficits_descoped')} -> {cur_descoped}; M6 non-extractive / NEVER #17)")
            return 1

    print(f"omega_deficit: PASS - W_in={d['W_in']} E={d['E']} S={d['S']} "
          f"E/W_in={d['ratio']:.3f} absolution={'YES' if d['absolution'] else 'NO'}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="recompute and write TASKS.md §H + proof")
    a = ap.parse_args()
    d = compute()
    if a.write:
        write_all(d)
        print(f"omega_deficit: wrote TASKS.md §H + proof/omega_deficit.json "
              f"(W_in={d['W_in']} E={d['E']} S={d['S']} E/W_in={d['ratio']:.3f})")
        return 0
    return check(d)


if __name__ == "__main__":
    sys.exit(main())
