#!/usr/bin/env python3
"""policy_block.py — the ONE machine-readable projection of the laws in DARKITH.md.

Why this exists, and what it is NOT
    DARKITH.md states its laws in prose headings. Prose is readable by a person and opaque to
    a machine: `tools/law_gate.py` has to re-parse headings with a regex, and every other gate
    invents its own idea of what a law is. The Prime Directive requires exactly one delimited,
    machine-readable policy section, parsed by exactly one strict parser.

    This tool GENERATES that section from the law headings already in DARKITH.md, and parses
    it back. It is a projection, never a second registry: the block carries a `source_sha256`
    of the law-bearing bytes it was derived from, and `--check` regenerates and compares, so a
    hand-edited block or a law changed without regenerating is a detectable defect. The block
    is written BETWEEN two marker lines; nothing outside them is touched.

Usage
    python3 tools/policy_block.py --write     regenerate the block from the law headings
    python3 tools/policy_block.py --check     gate: parses, fresh, ids unique, gates resolve
    python3 tools/policy_block.py --dump      print the parsed policy as JSON
    python3 tools/policy_block.py --selftest  prove the parser rejects each malformed form

Serialization: a flat YAML subset (key: value, and "- " list items) read by `parse_block`.
That parser is the single implementation. It rejects duplicate keys, duplicate ids, unknown
fields, malformed lines, and a stale block. It does not claim to be a general YAML parser.

Exit codes: 0 ok, 1 gate failure, 2 usage.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC = ROOT / "DARKITH.md"

BEGIN = "<!-- BEGIN MACHINE-READABLE POLICY (generated by tools/policy_block.py — do not edit) -->"
END = "<!-- END MACHINE-READABLE POLICY -->"

SCHEMA_NAME = "darkith-policy"
SCHEMA_VERSION = 1

# The law heading form the document already uses, and which law_gate.py also reads.
LAW = re.compile(r"───\s*((?:NEVER|MUST|SPI)-?\s*#?\s*\d+)\s*(?:\(([^)]*)\))?\s*───")
GATE = re.compile(r"tools/(?:[\w.-]+/)*[\w.-]+\.(?:py|sh|js)(?![\w.-])")
PREDICATE = re.compile(r"^\s*PREDICATE:\s*(.+)$", re.MULTILINE)
NOTE = "[NOTE: not yet gated]"

TOP_FIELDS = ("schema", "schema_version", "source_sha256", "law_count", "laws")
LAW_FIELDS = ("id", "title", "scope", "precedence", "gate", "failure", "acceptance", "status")
STATUSES = ("active", "retired", "historical")


def canonical_id(tok: str) -> str:
    m = re.match(r"(NEVER|MUST|SPI)\s*-?\s*#?\s*(\d+)$", tok.upper().strip())
    if not m:
        raise ValueError(f"unparseable law id: {tok!r}")
    kind, num = m.group(1), m.group(2)
    return f"SPI-{num}" if kind == "SPI" else f"{kind} #{num}"


def law_blocks(text: str):
    """Yield (id, title, body) for each law heading, in document order."""
    lines = text.splitlines()
    hits = [(i, m) for i, line in enumerate(lines) for m in [LAW.search(line)] if m]
    for idx, (i, m) in enumerate(hits):
        end = hits[idx + 1][0] if idx + 1 < len(hits) else len(lines)
        yield canonical_id(m.group(1)), (m.group(2) or "").strip(), "\n".join(lines[i:end])


def derive_laws(text: str) -> list[dict]:
    """Project each law heading into the fields the schema requires.

    scope/precedence/failure/acceptance are derived, not invented: precedence is document
    order (DARKITH.md states precedence as section order itself), the gate is the first gate
    the law body cites, and acceptance is the PREDICATE line when one is present.
    """
    laws = []
    seen: dict[str, int] = {}
    for order, (lid, title, body) in enumerate(law_blocks(text), 1):
        if lid in seen:
            raise ValueError(f"duplicate law id {lid} (headings {seen[lid]} and {order})")
        seen[lid] = order
        gates = GATE.findall(body)
        pred = PREDICATE.search(body)
        status = "historical" if NOTE in body else "active"
        laws.append(
            {
                "id": lid,
                "title": title,
                "scope": f"document-order-{order}",
                "precedence": order,
                "gate": gates[0] if gates else "",
                "failure": f"gate {gates[0]} exits non-zero" if gates else "no enforcing gate declared",
                "acceptance": pred.group(1).strip() if pred else "gate exits zero",
                "status": status,
            }
        )
    return laws


def render(laws: list[dict], source_sha: str) -> str:
    out = [BEGIN, "```yaml", f"schema: {SCHEMA_NAME}", f"schema_version: {SCHEMA_VERSION}"]
    out.append(f"source_sha256: {source_sha}")
    out.append(f"law_count: {len(laws)}")
    out.append("laws:")
    for law in laws:
        out.append(f"  - id: {json.dumps(law['id'])}")
        out.append(f"    title: {json.dumps(law['title'])}")
        out.append(f"    scope: {json.dumps(law['scope'])}")
        out.append(f"    precedence: {law['precedence']}")
        out.append(f"    gate: {json.dumps(law['gate'])}")
        out.append(f"    failure: {json.dumps(law['failure'])}")
        out.append(f"    acceptance: {json.dumps(law['acceptance'])}")
        out.append(f"    status: {law['status']}")
    out.append("```")
    out.append(END)
    return "\n".join(out)


class PolicyError(ValueError):
    pass


def _scalar(v: str):
    v = v.strip()
    if v.startswith('"'):
        try:
            return json.loads(v)
        except json.JSONDecodeError as e:
            raise PolicyError(f"malformed quoted scalar: {v[:60]!r} ({e.msg})") from None
    if re.fullmatch(r"-?\d+", v):
        return int(v)
    return v


def parse_block(text: str) -> dict:
    """The single strict parser. Raises PolicyError on anything it does not understand."""
    lines = text.splitlines()
    starts = [i for i, l in enumerate(lines) if l.strip() == BEGIN]
    ends = [i for i, l in enumerate(lines) if l.strip() == END]
    if len(starts) != 1:
        raise PolicyError(f"expected exactly one policy block, found {len(starts)}")
    if len(ends) != 1:
        raise PolicyError(f"expected exactly one policy terminator, found {len(ends)}")
    if ends[0] < starts[0]:
        raise PolicyError("policy terminator precedes its opener")

    body = lines[starts[0] + 1 : ends[0]]
    if not body or body[0].strip() != "```yaml":
        raise PolicyError("policy block must open a ```yaml fence")
    if body[-1].strip() != "```":
        raise PolicyError("policy block must close its ``` fence")

    doc: dict = {}
    laws: list[dict] = []
    cur: dict | None = None
    for raw in body[1:-1]:
        if not raw.strip():
            continue
        if raw.startswith("  - "):
            cur = {}
            laws.append(cur)
            raw = raw[4:]
        elif raw.startswith("    "):
            if cur is None:
                raise PolicyError(f"law field before any '- id': {raw.strip()[:50]}")
            raw = raw[4:]
        elif raw.startswith(" "):
            raise PolicyError(f"indentation not a multiple of 2: {raw!r}")
        else:
            cur = None
        if ":" not in raw:
            raise PolicyError(f"line is not 'key: value': {raw.strip()[:60]!r}")
        key, _, val = raw.partition(":")
        key = key.strip()
        if cur is not None:
            if key not in LAW_FIELDS:
                raise PolicyError(f"unknown law field {key!r}")
            if key in cur:
                raise PolicyError(f"duplicate law field {key!r} in {cur.get('id')}")
            cur[key] = _scalar(val)
        else:
            if key not in TOP_FIELDS:
                raise PolicyError(f"unknown top-level field {key!r}")
            if key in doc:
                raise PolicyError(f"duplicate top-level key {key!r}")
            if key == "laws":
                doc["laws"] = laws
            else:
                doc[key] = _scalar(val)

    doc.setdefault("laws", laws)
    if doc.get("schema") != SCHEMA_NAME:
        raise PolicyError(f"schema must be {SCHEMA_NAME!r}, got {doc.get('schema')!r}")
    if doc.get("schema_version") != SCHEMA_VERSION:
        raise PolicyError(f"schema_version must be {SCHEMA_VERSION}")
    seen_ids: set[str] = set()
    for law in doc["laws"]:
        missing = [f for f in ("id", "gate", "status", "precedence") if f not in law]
        if missing:
            raise PolicyError(f"law {law.get('id', '?')} missing fields {missing}")
        if law["id"] in seen_ids:
            raise PolicyError(f"duplicate law id {law['id']!r}")
        seen_ids.add(law["id"])
    return doc


def validate(doc: dict) -> list[str]:
    """Semantic checks that need the tree. Returns a list of problems."""
    problems: list[str] = []
    ids = [law["id"] for law in doc["laws"]]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        problems.append(f"duplicate law ids: {sorted(dupes)}")
    if doc.get("law_count") != len(doc["laws"]):
        problems.append(f"law_count {doc.get('law_count')} != {len(doc['laws'])} parsed laws")
    precs = [law["precedence"] for law in doc["laws"]]
    if sorted(precs) != list(range(1, len(precs) + 1)):
        problems.append("precedence is not a total order 1..N (ambiguous precedence)")
    for law in doc["laws"]:
        if law["status"] not in STATUSES:
            problems.append(f"{law['id']}: invalid status {law['status']!r}")
        g = law["gate"]
        if not g:
            if law["status"] == "active":
                problems.append(f"{law['id']}: active law has no enforcing gate")
            continue
        if not (ROOT / g).exists():
            problems.append(f"{law['id']}: gate {g} does not exist on disk")
    return problems


def read_doc() -> str:
    return DOC.read_text(encoding="utf-8")


def block_region(text: str) -> tuple[int, int] | None:
    lines = text.splitlines(keepends=True)
    starts = [i for i, l in enumerate(lines) if l.strip() == BEGIN]
    ends = [i for i, l in enumerate(lines) if l.strip() == END]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        return None
    return starts[0], ends[0]


def _law_bearing_sha(laws: list[dict]) -> str:
    """Fingerprint of the LAW CONTENT, not of document bytes.

    Hashing the file (or the file minus the block) makes the pointer sensitive to seam
    whitespace, so inserting the block changes the very bytes the block claims to describe.
    The laws themselves are the identity: hash the derived rows, canonically ordered.
    """
    canon = json.dumps(laws, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canon.encode("utf-8")).hexdigest()


def cmd_write() -> int:
    text = read_doc()
    laws = derive_laws(text)
    region = block_region(text)
    if region:
        sha = _law_bearing_sha(laws)
        lines = text.splitlines(keepends=True)
        new = "".join(lines[: region[0]]) + render(laws, sha) + "\n" + "".join(lines[region[1] + 1 :])
    else:
        marker = "\n---\n\n# PART 1"
        idx = text.find(marker)
        if idx < 0:
            print("policy_block: cannot find insertion point (before PART 1)", file=sys.stderr)
            return 2
        sha = _law_bearing_sha(laws)
        new = text[:idx] + "\n\n" + render(laws, sha) + "\n" + text[idx:]
    DOC.write_text(new, encoding="utf-8")
    print(f"policy_block: wrote {len(laws)} laws into DARKITH.md (source_sha256 {sha[:16]}…)")
    return 0


def cmd_check() -> int:
    text = read_doc()
    try:
        doc = parse_block(text)
    except PolicyError as e:
        print(f"policy_block: FAIL — {e}")
        return 1
    problems = validate(doc)
    region = block_region(text)
    if region is None:
        problems.append("policy block markers are missing or duplicated")
    else:
        expect = render(derive_laws(text), _law_bearing_sha(derive_laws(text)))
        lines = text.splitlines(keepends=True)
        actual = "".join(lines[region[0] : region[1] + 1]).rstrip("\n")
        if actual != expect:
            problems.append("block is stale vs the law headings (run --write)")
    if problems:
        print("policy_block: FAIL")
        for p in problems:
            print(f"  - {p}")
        return 1
    print(
        f"policy_block: PASS — {len(doc['laws'])} laws, ids unique, precedence total, "
        f"every gate resolves, block fresh"
    )
    return 0


def cmd_dump() -> int:
    print(json.dumps(parse_block(read_doc()), indent=1))
    return 0


def cmd_selftest() -> int:
    """Prove the parser rejects each malformed form. A parser that cannot fail is not strict."""
    good_law = (
        '  - id: "MUST #1"\n    title: "t"\n    scope: "s"\n    precedence: 1\n'
        '    gate: "tools/law_gate.py"\n    failure: "f"\n    acceptance: "a"\n    status: active'
    )

    def mk(*laws: str, top: str = "") -> str:
        return "\n".join(
            [BEGIN, "```yaml", f"schema: {SCHEMA_NAME}", f"schema_version: {SCHEMA_VERSION}",
             "source_sha256: deadbeef", f"law_count: {len(laws)}", top + "laws:", *laws,
             "```", END]
        )

    cases = [
        ("valid baseline", mk(good_law), False),
        ("duplicate top-level key", mk(good_law, top="schema_version: 1\n"), True),
        ("duplicate law id", mk(good_law, good_law), True),
        ("unknown top-level field", mk(good_law, top="bogus: 1\n"), True),
        ("unknown law field", mk(good_law.replace("status: active", "status: active\n    bogus: 1")), True),
        ("duplicate law field", mk(good_law.replace("status: active", "status: active\n    status: active")), True),
        ("malformed quoted scalar", mk(good_law.replace('title: "t"', 'title: "unclosed')), True),
        ("no yaml fence", mk(good_law).replace("```yaml", "```json"), True),
        ("two blocks", mk(good_law) + "\n" + mk(good_law), True),
        ("law field before id", "\n".join([BEGIN, "```yaml", f"schema: {SCHEMA_NAME}",
                                           f"schema_version: {SCHEMA_VERSION}",
                                           "source_sha256: x", "law_count: 1", "laws:",
                                           '    id: "MUST #1"', "```", END]), True),
    ]
    bad = 0
    for name, text, want_fail in cases:
        try:
            parse_block(text)
            got_fail = False
        except PolicyError:
            got_fail = True
        ok = got_fail == want_fail
        print(f"  [{'ok' if ok else 'XX'}] {name}: {'rejected' if got_fail else 'accepted'}")
        bad += 0 if ok else 1
    if bad:
        print(f"policy_block selftest: FAIL — {bad} case(s) wrong")
        return 1
    print(f"policy_block selftest: PASS — {len(cases)} cases")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--dump", action="store_true")
    g.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.write:
        return cmd_write()
    if args.check:
        return cmd_check()
    if args.dump:
        return cmd_dump()
    if args.selftest:
        return cmd_selftest()
    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
