#!/usr/bin/env python3
"""doc_index.py — the universal knowledgebase index (AGENTS.md §22 DEDUPLICATION).

The repo accumulated documents faster than it indexed them: five standalone HTML
deliverables at the root, a `docs/` corpus, a `proof/` evidence pile, and governance docs —
with no single place that said which file is the ONE source for each topic and which are
generated copies. That is the "documents all over the place" defect: not that files exist,
but that a reader cannot tell canonical from copy.

This tool makes the structure convergent and self-checking. Every tracked document is
classified into exactly ONE role:

  CANONICAL     the single source of truth for a topic        (edit here)
  SESSION-MEMORY the agent's read-first repo knowledge        (edit here)
  RECOVERY      the fresh-VM recovery protocol                (edit here)
  BOARD         the durable task board                        (edit here)
  LEDGER        the machine-readable deficit ledger           (edit here)
  REFERENCE     preserved source material (NT corpus, spec)   (read-only)
  DELIVERABLE   a standalone shippable artifact (the apps)    (edit the generator)
  EVIDENCE      immutable proof/log output under proof/       (append-only)
  INDEX         this file (generated)                          (never edit)
  MIRROR        a generated byte-identical copy of a source    (never edit)

A document that matches no role is an ORPHAN — a file nobody owns and nobody cites. Orphans
fail. The index (docs/INDEX.md) is regenerated from the tracked tree, so it is deterministic:
two runs diff clean, and any new doc must declare its role or CI goes red.

Usage:
  python3 tools/doc_index.py            # check: index up to date AND no orphans
  python3 tools/doc_index.py --write    # regenerate docs/INDEX.md
Exit: 0 = converged; 1 = orphan(s) or a stale index.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
INDEX = ROOT / "docs/INDEX.md"

DOC_EXT = (".md", ".txt", ".html")
# Config/data files that share a doc extension but are not documents.
NOT_DOCS = {"requirements-dev.txt", "requirements.txt", "deps.txt"}

# role -> (rule, purpose, readers). Ordered: the first rule that matches wins.
ROLES: list[tuple[str, str, str, str]] = [
    ("CANONICAL", "DARKITH.md",
     "the single source of truth: version, reconciliation, deficits, laws", "owner, agents, auditors"),
    ("SESSION-MEMORY", "AGENTS.md",
     "repo knowledge + binding laws; read-first for every session", "agents"),
    ("RECOVERY", "RESUME.md",
     "the fresh-VM recovery protocol (restore, save, converge)", "agents"),
    ("BOARD", "TASKS.md",
     "the durable task board (what is done / todo / blocked)", "owner, agents"),
    ("LEDGER", "DEFICITS.json",
     "the machine-readable deficit ledger (NEVER #17)", "agents, stall_gate"),
    ("INDEX", "docs/INDEX.md",
     "this generated map of the knowledgebase", "owner, agents, auditors"),
]


def tracked() -> list[str]:
    try:
        out = subprocess.run(["git", "-C", str(ROOT), "ls-files"],
                             capture_output=True, text=True, check=True).stdout
        files = [p for p in out.splitlines() if p]
        if files:
            return files
    except Exception:
        pass
    return [str(p.relative_to(ROOT)) for p in ROOT.rglob("*")
            if p.is_file() and ".git" not in p.parts and "node_modules" not in p.parts]


def is_doc(path: str) -> bool:
    if pathlib.PurePosixPath(path).name in NOT_DOCS:
        return False
    return path.endswith(DOC_EXT)


def role_of(path: str) -> str | None:
    for role, fname, _, _ in ROLES:
        if path == fname:
            return role
    if path.startswith("proof/"):
        return "EVIDENCE"
    if path.startswith("docs/"):
        return "REFERENCE"
    if path == "DARKITH OMEGA repo.txt":
        return "REFERENCE"
    # generated copies of a tracked source (the synchrony mirror pair)
    if path.startswith("app/src/main/assets/") and path.endswith(".html"):
        return "MIRROR"
    # standalone shippable surfaces at the repo root
    if "/" not in path and path.endswith(".html"):
        return "DELIVERABLE"
    return None


def purpose_of(path: str) -> str:
    if path == "docs/INDEX.md":
        return "this generated map (regenerate with --write)"
    if path.startswith("proof/"):
        return "proof / evidence log (append-only)"
    if path.startswith("docs/nt/"):
        return "NT corpus source"
    if path.startswith("docs/"):
        return "reference document"
    if path.startswith("app/src/main/assets/"):
        return "generated copy (see tools/inject_synchrony.py, tools/synchrony_gate.py)"
    if path.endswith(".html"):
        return "standalone offline app (single file, zero-dependency)"
    return "reference"


def collect() -> tuple[dict[str, list[str]], list[str]]:
    by_role: dict[str, list[str]] = {}
    orphans: list[str] = []
    for p in sorted(tracked()):
        if not is_doc(p):
            continue
        role = role_of(p)
        if role is None:
            orphans.append(p)
        else:
            by_role.setdefault(role, []).append(p)
    return by_role, orphans


def corpus_summary() -> tuple[list[str], dict[str, int]]:
    """The NT corpus files and the SAVF-graded claim counts (the live corpus size)."""
    nt = sorted(p.name for p in (ROOT / "docs/nt").glob("NT-*") if p.is_file())
    counts: dict[str, int] = {}
    claims = ROOT / "proof/nt_claims.json"
    if claims.is_file():
        try:
            import json
            for c in json.loads(claims.read_text(encoding="utf-8")):
                counts[c.get("kind", "?")] = counts.get(c.get("kind", "?"), 0) + 1
        except Exception:
            pass
    return nt, counts


def render(by_role: dict[str, list[str]], orphans: list[str]) -> str:
    nt, counts = corpus_summary()
    total_claims = sum(counts.values())
    lines = [
        "# docs/INDEX.md — the DARKITH knowledgebase index",
        "",
        "> **GENERATED by `tools/doc_index.py`. Do not edit by hand.**",
        "> Regenerate: `python3 tools/doc_index.py --write`. Gate: `python3 tools/doc_index.py`.",
        "",
        "This is the ONE place that says which file is the source for each topic and which files",
        "are generated copies. Every tracked document carries exactly one role; a document that",
        "carries none is an orphan and fails the gate.",
        "",
        "## The knowledgebase spine",
        "",
        "The knowledgebase is not a static pile of files. It is the NT corpus (an evolving law",
        "layer), graded by SAVF (rigorous self-scrutiny), enforced by gates (a law that is not a",
        "gate is a note), and summarised in the state layer. Each layer is one file family:",
        "",
        "| layer | what it is | the one source |",
        "|---|---|---|",
        f"| LAW | the NT corpus — noveltreatise laws, reconciled and carried | `docs/nt/` ({len(nt)} files) |",
        "| SCRUTINY | SAVF grades every claim; contradictions resolved to absolution | `savf.py` / `savf.html` |",
        f"| CLAIMS | the corpus as machine-graded claims (A/W/R/C) | `proof/nt_claims.json` ({total_claims} claims) |",
        "| ENFORCEMENT | every law names a gate; CI runs them | `tools/*_gate.*`, `tools/ci.sh` |",
        "| STATE | version, reconciliation, deficits, laws | `DARKITH.md` |",
        "| BOARD | what is done / todo / blocked | `TASKS.md` |",
        "| LEDGER | named deficiencies, closed or descoped | `DEFICITS.json` |",
        "",
        "The corpus grows by adding NT files and their claims; the count below is read live from",
        "`proof/nt_claims.json`, so the index reports the corpus size, not a frozen guess:",
        "",
        f"- claims: {total_claims} total "
        f"(A analysis {counts.get('A', 0)}, W witness {counts.get('W', 0)}, "
        f"R derived {counts.get('R', 0)}, C contradiction {counts.get('C', 0)})",
        "- gate: `python3 tools/nt_gate.py` (fails unless every contradiction is resolved)",
        "",
        "## The NT corpus (LAW layer)",
        "",
        "| file | purpose |",
        "|---|---|",
    ]
    for name in nt:
        lines.append(f"| `docs/nt/{name}` | " +
                     ("the corpus index + NT→gate map" if name == "NT-INDEX.md" else "NT law source") + " |")

    lines += [
        "",
        "## The convergent structure (one role per file)",
        "",
        "| role | the one file | purpose | readers |",
        "|---|---|---|---|",
    ]
    for role, fname, purpose, readers in ROLES:
        lines.append(f"| **{role}** | `{fname}` | {purpose} | {readers} |")

    order = ["CANONICAL", "SESSION-MEMORY", "RECOVERY", "BOARD", "LEDGER", "INDEX",
             "REFERENCE", "DELIVERABLE", "MIRROR", "EVIDENCE"]
    for role in order:
        files = by_role.get(role)
        if not files:
            continue
        lines += ["", f"## {role}", ""]
        for f in files:
            lines.append(f"- `{f}` — {purpose_of(f)}")

    lines += ["", "## Orphan check", ""]
    if orphans:
        lines.append(f"**{len(orphans)} orphan(s) — a document with no declared role:**")
        lines += [f"- `{o}`" for o in orphans]
        lines.append("")
        lines.append("Classify it in `tools/doc_index.py` (add a role) or remove it.")
    else:
        lines.append("PASS — every tracked document has a declared role; no orphans.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="regenerate docs/INDEX.md")
    a = ap.parse_args()

    by_role, orphans = collect()
    text = render(by_role, orphans)

    if a.write:
        INDEX.parent.mkdir(parents=True, exist_ok=True)
        INDEX.write_text(text, encoding="utf-8")
        n = sum(len(v) for v in by_role.values())
        print(f"doc_index: wrote docs/INDEX.md ({n} documents, {len(orphans)} orphan(s))")
        return 1 if orphans else 0

    rc = 0
    if orphans:
        print(f"doc_index: FAIL — {len(orphans)} orphan document(s) with no declared role:")
        for o in orphans:
            print(f"  - {o}")
        rc = 1
    if not INDEX.is_file() or INDEX.read_text(encoding="utf-8") != text:
        print("doc_index: FAIL — docs/INDEX.md is missing or stale (run: python3 tools/doc_index.py --write)")
        rc = 1
    if rc == 0:
        n = sum(len(v) for v in by_role.values())
        print(f"doc_index: PASS — {n} documents, all classified; docs/INDEX.md is current")
    return rc


if __name__ == "__main__":
    sys.exit(main())
