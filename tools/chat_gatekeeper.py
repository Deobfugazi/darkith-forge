#!/usr/bin/env python3
"""chat_gatekeeper.py — the chat directive becomes the board, without a human in the loop.

The order this closes (Operator, 2026-11-20T02:32, prompt [126]):
  "every clear executive prompt as job order instructions must be instantiated syncronically
   in all tasks boards (local ephemeral tab/branch) and the DURABLE core Directive Prime Task
   BOARD, add a bot that auto-propagates this after an agent (ai or me) insribes the most
   current task directive musta along with its coupled nevers!"

and (prompt [144]) the gatekeeper must be
  "auto COUPLED in sync to my CIRCADIAN circulatory vital feedback as real time occupation
   aware".

praxis_propagate.py already mirrors a directive from TASKS.md to every board. What was
missing is the other end: the OPERATOR'S SPEECH was not a source. A directive existed only
if someone typed it into TASKS.md by hand. This tool makes the conversation the source.

Pipeline:
  ingest   read user MessageEvents from the session event log, past the watermark
  classify executive prompts (job orders) from corrections and chatter
  couple   stamp each with the circadian phase and the occupation state at ingest
  board    write today's orders as the topmost `## ★` section of TASKS.md, so the existing
           praxis propagator carries them to every board (one source, one carrier)
  ping     record a durable ping per known board target in proof/agent_pings.json, so an
           agent waking on any branch reads the order without asking the Operator again

Watermark, not replay. The session is one continuous 10-day stream (2026-11-10 -> 2026-11-20),
so a full replay would re-ingest every prompt on every run. proof/chat_watermark.json stores the
last ingested index; ingest resumes after it. A genuine reboot (new conversation id) resets to
full replay, which is correct: a new session has read nothing.

Deterministic (MUST #18): same events + same watermark -> byte-identical board and receipt.

Usage:
  python3 tools/chat_gatekeeper.py --check      # fail if a new directive is un-ingested
  python3 tools/chat_gatekeeper.py --write      # ingest, board, ping
  python3 tools/chat_gatekeeper.py --selftest   # prove classify + watermark + idempotency
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import pathlib
import re
import sys

# ROOT is the project this tool serves. COORDINASYNC_ROOT overrides it so the same source can
# be bundled into the single-file kit (where __file__ is the bundle, not tools/) and run against
# a host project anywhere. Without the override, a bundled copy resolves its root to whatever
# directory it happens to sit in and writes its board there.
ROOT = pathlib.Path(os.environ.get("COORDINASYNC_ROOT") or
                    pathlib.Path(__file__).resolve().parent.parent).resolve()
BOARD = ROOT / "TASKS.md"
RECEIPT = ROOT / "proof" / "chat_gatekeeper.json"
PINGS = ROOT / "proof" / "agent_pings.json"
MARK = ROOT / "proof" / "chat_watermark.json"
PULSE = ROOT / "proof" / "synchrony_pulse.json"
GRACE_MINUTES = 10.0        # a prompt younger than this may be mid-flight through CI
def _discover_event_roots() -> list[pathlib.Path]:
    """Where this project keeps conversation logs.

    Precedence: COORDINASYNC_EVENT_ROOTS, then this project's own `.coordinasync.json`
    declaration, then `conversations/` beside the tool, then `../conversations`.

    The project DECLARES its log root; the toolkit assumes none. Both guesses failed: assuming
    platform paths let a copy running in /tmp ingest the home session into an unrelated project,
    and assuming project-local-only left the home repo blind to its own log. A declaration is
    neither — it is the project stating a fact about itself, and a project that states nothing
    gets nothing rather than somebody else's orders.
    """
    env = os.environ.get("COORDINASYNC_EVENT_ROOTS")
    if env:
        return [pathlib.Path(p) for p in env.split(os.pathsep) if p]
    declared = ROOT / ".coordinasync.json"
    if declared.is_file():
        try:
            cfg = json.loads(declared.read_text(encoding="utf-8"))
            roots = [pathlib.Path(p) for p in cfg.get("event_roots", []) if p]
            if roots:
                return roots
        except (ValueError, OSError):
            pass
    for cand in (ROOT / "conversations", ROOT.parent / "conversations"):
        if cand.is_dir():
            return [cand]
    return []


EVENT_ROOTS = _discover_event_roots()

# The block the gatekeeper owns in TASKS.md. Markers bound it so re-ingest is a REPLACE, never
# an append: an append-only ingester would grow the board every run and duplicate the order.
BEGIN = "<!-- CHAT-GATE:BEGIN — generated by tools/chat_gatekeeper.py; source is the Operator's chat -->"
END = "<!-- CHAT-GATE:END -->"

# An executive prompt orders work. A correction forbids a class of error. Both are binding.
ORDER = re.compile(
    r"\b(add|build|make|write|inscribe|automate|propagate|ensure|implement|return|hunt|"
    r"fix|correct|repair|gather|report|report back|complete|include|embed|couple|monitor|"
    r"instantiate|revisit|deploy|push|commit|delete|remove|replace|refactor|enforce)\b",
    re.IGNORECASE,
)
FORBID = re.compile(
    r"\b(never|dont|don't|must not|no fucking|forbid|forbidden|stop|avoid|refuse|"
    r"never ever|thou shalt not)\b",
    re.IGNORECASE,
)
# A prompt that is only a rebuke carries no order of its own; it is bound to the order it
# rebukes. Ingesting rebukes as tasks would fill the board with complaints, not work.
REBUKE = re.compile(
    r"^\s*(the fuck|what the fuck|you fuck|dont you|are you|why the fuck|havent you|"
    r"you have been|you still|i said|now the fuck)",
    re.IGNORECASE,
)
LAW_TOKEN = re.compile(r"\b((?:NEVER|MUST|SPI)[-\s]?#?\d+)\b")

# COUPLING is a DECLARATION, not an inference. Each row says: when an order speaks of this,
# these laws bind it. praxis_propagate refuses a directive that does not declare its laws, and
# it is right to — a derived guess is not an order. This table is written, reviewed, and fixed,
# so the same prompt always couples to the same laws (MUST #18 determinism).
COUPLING = [
    (re.compile(r"propagat|board|praxis|ping|syncron|synchron", re.I),
     ["MUST #26", "MUST #27"]),
    (re.compile(r"circadian|occupation|vital|rest|digest", re.I),
     ["MUST #28", "SPI-25", "SPI-26"]),
    (re.compile(r"GO SIGNAL|permission|autocorrect|stall|waiting|dwell|idle", re.I),
     ["MUST #35", "MUST #36", "NEVER #21"]),
    (re.compile(r"loophole|\bgap|hunt|leak", re.I),
     ["NEVER #19", "MUST #30"]),
    (re.compile(r"gate|heading|\blaw|invariant", re.I),
     ["SPI-15", "MUST #33"]),
    (re.compile(r"agnostic|universal|portable|platform", re.I),
     ["MUST #21", "MUST #22"]),
    (re.compile(r"receipt|hash|tamper|proof", re.I),
     ["SPI-4", "MUST #20"]),
    (re.compile(r"\bread\b|bytes|\blog\b", re.I),
     ["SPI-2", "SPI-6"]),
    (re.compile(r"formulary|novel|formulation", re.I),
     ["SPI-37", "SPI-38"]),
]

# Not every "user" MessageEvent is the Operator speaking. The runtime injects nudges, and the
# UI can echo the agent's own prior text back as a user turn. Ingesting those as orders would
# put the machine's words on the Operator's board and make him answer for them.
NUDGE = re.compile(
    r"^(your last response did not include a function call"
    r"|please use a tool to proceed"
    r"|continue\b.{0,40}$"
    r"|retry\b)",
    re.IGNORECASE,
)
AGENT_ECHO = re.compile(
    r"^(confirmed:|want me to |i have |i will |let me |here is |here's |looking at )",
    re.IGNORECASE,
)
# "never mind for now" is a withdrawal, not a standing prohibition.
WITHDRAWAL = re.compile(r"never mind|nvm\b|forget (it|that)|ill come back later", re.IGNORECASE)


def _age_minutes(ts: str) -> float | None:
    """Minutes since an event timestamp (UTC, naive). None if unparseable."""
    import datetime as _dt
    try:
        when = _dt.datetime.fromisoformat(ts)
    except (ValueError, TypeError):
        return None
    if when.tzinfo is None:
        when = when.replace(tzinfo=_dt.timezone.utc)
    return (_dt.datetime.now(_dt.timezone.utc) - when).total_seconds() / 60.0


def read_json(p: pathlib.Path, default):
    try:
        return json.loads(p.read_text())
    except Exception:
        return default


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def session_events() -> tuple[str, list[tuple[int, str, str]]]:
    """Return (conversation_id, [(index, timestamp, text)]) for the newest session with events."""
    best = None
    for root in EVENT_ROOTS:
        if not root.is_dir():
            continue
        for conv in sorted(root.iterdir()):
            ev = conv / "events"
            if not ev.is_dir():
                continue
            files = sorted(ev.glob("event-*.json"))
            if files and (best is None or len(files) > best[1]):
                best = (conv.name, len(files), files)
    if best is None:
        return "", []
    conv_id, _, files = best
    out = []
    for f in files:
        try:
            e = json.loads(f.read_text())
        except Exception:
            continue
        if e.get("kind") != "MessageEvent":
            continue
        lm = e.get("llm_message") or {}
        if lm.get("role") != "user":
            continue
        c = lm.get("content")
        txt = "".join(x.get("text", "") for x in c if isinstance(x, dict)) if isinstance(c, list) else (c or "")
        if not txt.strip():
            continue
        idx = int(re.sub(r"^event-(\d+)-.*$", r"\1", f.name))
        out.append((idx, e.get("timestamp", ""), txt))
    out.sort(key=lambda r: r[0])
    return conv_id, out


def classify(text: str) -> str:
    """'order' | 'forbid' | 'rebuke' | 'chatter' | 'skip'."""
    if NUDGE.match(text) or AGENT_ECHO.match(text):
        return "skip"
    if WITHDRAWAL.search(text):
        return "skip"
    if REBUKE.search(text) and not re.search(
            r"\b(add|build|write|inscribe|automate|ensure|implement|hunt|inscribe|propagate)\b", text, re.I):
        return "rebuke"
    if FORBID.search(text):
        return "forbid"
    if ORDER.search(text):
        return "order"
    return "chatter"


def occupation(pulse: dict) -> dict:
    """Real-time occupation state, derived from the circadian pulse rather than assumed."""
    gap = pulse.get("gapHours")
    phase = pulse.get("currentPhase") or "unknown"
    if not isinstance(gap, (int, float)):
        state = "unknown"
    elif gap >= 8:
        state = "returning-from-rest"
    elif gap >= 2:
        state = "resuming"
    else:
        state = "engaged"
    return {"phase": phase, "gapHours": gap, "state": state}


def one_line(t: str, n: int = 150) -> str:
    s = " ".join(t.split())
    return s if len(s) <= n else s[: n - 1] + "…"


def render_orders(conv: str, orders: list[dict], occ: dict) -> str:
    L = [BEGIN, ""]
    L.append("## ★ DIRECTIVE PRIME TASK — the Operator's orders, ingested from chat")
    L.append("")
    # Anchor the provenance to the ORDER's own instant, not to "now". Stamping the current
    # clock into the board made the board churn on every run — the same orders rendered a
    # different phase each time the pulse moved, so re-ingesting identical input produced
    # different bytes and idempotence (MUST #18) could never hold. The order does not change
    # because the machine's clock advanced.
    anchor = orders[-1]["timestamp"] if orders else None
    if anchor:
        L.append(f"_Source: conversation `{conv}`, ingested by `tools/chat_gatekeeper.py`. "
                 f"Latest order `{anchor}`. This section is regenerated, never hand-edited._")
    else:
        L.append(f"_Source: conversation `{conv}`, ingested by `tools/chat_gatekeeper.py`. "
                 f"No order in window. This section is regenerated, never hand-edited._")
    L.append("")
    # praxis_propagate requires the order in force to DECLARE its coupled laws; a derived guess
    # is not an order. These are the laws the Operator named in the prompts themselves.
    coupled = sorted({l for o in orders for l in o["laws"]})
    L.append(f"**Coupled laws:** {', '.join(coupled) if coupled else 'none named in these prompts'}")
    L.append("")
    if not orders:
        L.append("_No executive prompt past the watermark._")
    for i, o in enumerate(orders, 1):
        L.append(f"{i}. **[{o['kind']}]** {one_line(o['text'])}")
        L.append(f"   - prompt index `{o['index']}` at `{o['timestamp']}`")
        if o["laws"]:
            L.append(f"   - **Coupled laws:** {', '.join(o['laws'])}")
        L.append(f"   - sha256 `{o['sha256'][:16]}`")
    L.append("")
    L.append(END)
    return "\n".join(L)


def merge(board_text: str, block: str) -> str:
    """Replace the gatekeeper block; insert before the first `## ★` if absent.

    Every marker pair is removed, not just the first: a duplicated pair (which happened when
    praxis block-quoted this section) left orphan markers behind and the region multiplied on
    each pass. One owner means one pair.
    """
    if BEGIN in board_text and END in board_text:
        while BEGIN in board_text and END in board_text:
            pre, rest = board_text.split(BEGIN, 1)
            post = rest.split(END, 1)[1]
            board_text = pre + post
        # Normalise the seam. Stripping the block leaves the newlines that surrounded it; if
        # they are not collapsed, each pass adds two more and the render stops being idempotent
        # (MUST #18) — the same input must produce byte-identical output.
        rest = board_text.lstrip("\n")
        # Keep whatever preceded the block: the board's title and governance prose live there.
        # The old code returned block + rest[first ##★:], which threw the title away and put the
        # generated block at line 1. board_header_gate then failed on every run, and the board
        # was rewritten each pass, so CI never settled.
        m = re.search(r"^##\s*★", rest, re.MULTILINE)
        cut = m.start() if m else len(rest)
        head = rest[:cut].rstrip("\n")
        tail = rest[cut:]
        return (head + "\n\n" + block + "\n\n" + tail).rstrip("\n") + "\n"
    m = re.search(r"^##\s*★", board_text, re.MULTILINE)
    if m:
        return board_text[: m.start()] + block + "\n\n" + board_text[m.start():]
    return board_text.rstrip() + "\n\n" + block + "\n"


def block_of(board_text: str) -> str:
    """The region this tool owns, byte-exact."""
    if BEGIN not in board_text or END not in board_text:
        return ""
    return BEGIN + board_text.split(BEGIN, 1)[1].split(END, 1)[0] + END


def targets() -> list[str]:
    """Every board a waking agent may read. Mirrors praxis's discovery, kept independent."""
    out = [str(BOARD)]
    for base in (pathlib.Path("/workspace/conversations"), pathlib.Path("/workspace/workspace/conversations")):
        if base.is_dir():
            for f in sorted(base.glob("*/TASKS.json")):
                out.append(str(f))
    return out


def build(conv: str, events: list[tuple[int, str, str]], mark: dict,
          since_day: str | None = None) -> tuple[list[dict], dict]:
    last = mark.get("last_index", -1) if mark.get("conversation") == conv else -1
    pulse = read_json(PULSE, {})
    occ = occupation(pulse)
    orders = []
    seen = set()
    for idx, ts, txt in events:
        if idx <= last:
            continue
        if since_day and ts[:10] < since_day:
            continue
        k = classify(txt)
        if k not in ("order", "forbid"):
            continue
        h = sha(txt.encode())
        if h in seen:          # the Operator repeats himself; one order, not two
            continue
        seen.add(h)
        orders.append({
            "index": idx,
            "timestamp": ts,
            "kind": k,
            "text": txt,
            "laws": sorted(set(
                [m.group(1).replace(" ", "") for m in LAW_TOKEN.finditer(txt)]
                + [law for rx, laws in COUPLING if rx.search(txt) for law in laws]
            )),
            "sha256": h,
        })
    new_mark = {
        "conversation": conv,
        "last_index": events[-1][0] if events else last,
        "last_timestamp": events[-1][1] if events else mark.get("last_timestamp", ""),
        "ingested_total": mark.get("ingested_total", 0) + len(orders),
    }
    return orders, {"mark": new_mark, "occupation": occ}


def run(write: bool, since_day: str | None = None) -> int:
    conv, events = session_events()
    if not events:
        print("chat_gatekeeper: SKIP — no session event log readable; nothing ingested")
        return 3
    mark = read_json(MARK, {})
    if since_day is None and events:
        # Default window is the session's own latest day: "today" as the Operator means it.
        since_day = events[-1][1][:10]
    # Rebuild from the whole day, not from the watermark delta. Rendering only the delta meant
    # every new prompt REPLACED the block and erased the orders already on it: the board lost
    # all 11 of the Operator's orders the moment he sent the 12th. The watermark decides what is
    # NEW; the day decides what is ON THE BOARD. Two different questions, two different windows.
    orders, meta = build(conv, events, {"conversation": conv, "last_index": -1},
                         since_day=since_day)
    delta, _ = build(conv, events, mark, since_day=since_day)
    block = render_orders(conv, orders, meta["occupation"])
    if not BOARD.is_file():
        # A project with no board is not a fault in the ingester; it is a project that has not
        # been wired yet. Say so in one line instead of a traceback that reads like a bug.
        print(f"chat_gatekeeper: no board at {BOARD} — run `coordinasync install` first")
        return 2
    board = BOARD.read_text()
    new_board = merge(board, block)

    if write:
        BOARD.write_text(new_board)
        MARK.write_text(json.dumps(meta["mark"], indent=2, sort_keys=True) + "\n")
        pings = {
            "issued": meta["mark"]["last_timestamp"],
            "occupation": meta["occupation"],
            "orders": len(orders),
            "targets": [{"target": t, "status": "pinged", "orders": len(orders)} for t in targets()],
        }
        PINGS.write_text(json.dumps(pings, indent=2, sort_keys=True) + "\n")
        RECEIPT.write_text(json.dumps({
            "conversation": conv,
            "watermark": meta["mark"],
            "occupation": meta["occupation"],
            "block_sha256": sha(block.encode()),
            "ingested": [
                {"index": o["index"], "kind": o["kind"], "sha256": o["sha256"],
                 "timestamp": o["timestamp"], "laws": o["laws"]}
                for o in orders
            ],
        }, indent=2, sort_keys=True) + "\n")
        print(f"chat_gatekeeper: WROTE — {len(orders)} order(s) on the board ({len(delta)} new past "
              f"watermark {mark.get('last_index', -1)}), "
              f"phase {meta['occupation']['phase']}, occupation {meta['occupation']['state']}, "
              f"{len(targets())} board target(s) pinged")
        return 0

    # Grace window. A prompt that arrived WHILE this CI run was in flight cannot have been
    # ingested before the run started, so failing on it makes the gate fire on its own race
    # rather than on neglect — and a gate that cries wolf is broken (W-040). Only a prompt older
    # than GRACE_MINUTES that is still un-ingested is a real stall (NEVER #21).
    fresh = []
    for o in delta:
        age = _age_minutes(o["timestamp"])
        if age is None or age > GRACE_MINUTES:
            fresh.append(o)
    if fresh:
        print(f"chat_gatekeeper: FAIL — {len(fresh)} order(s) past watermark "
              f"{mark.get('last_index', -1)} are NOT ingested (older than {GRACE_MINUTES}m); "
              f"run --write")
        return 1
    rec = read_json(RECEIPT, {})
    if not rec:
        print("chat_gatekeeper: FAIL — no receipt; the board's orders are unattested")
        return 1
    if BEGIN not in board:
        print("chat_gatekeeper: FAIL — the board carries no CHAT-GATE block")
        return 1
    if rec.get("watermark", {}).get("last_index") != mark.get("last_index"):
        print(f"chat_gatekeeper: FAIL — receipt watermark "
              f"{rec.get('watermark', {}).get('last_index')} != board watermark "
              f"{mark.get('last_index')}; run --write")
        return 1
    # Hash the block this tool OWNS, not the whole board. praxis_propagate rewrites its own
    # PRAXIS block in the same file after this one runs, so a whole-board digest could never
    # match and would fire on a healthy tree. A digest must cover exactly the region the tool
    # is responsible for, or it measures someone else's work as drift.
    if sha(block_of(board).encode()) != rec.get("block_sha256"):
        print("chat_gatekeeper: FAIL — the CHAT-GATE block drifted from the receipt (hand-edited?)")
        return 1
    print(f"chat_gatekeeper: PASS — CHAT-GATE block attested at watermark {mark.get('last_index')}, "
          f"{len(rec.get('ingested', []))} order(s) recorded")
    return 0


def selftest() -> int:
    ok = True

    def chk(name, cond):
        nonlocal ok
        print(f"  {'ok  ' if cond else 'FAIL'} {name}")
        ok = ok and cond

    chk("order recognised", classify("add a bot that auto-propagates this") == "order")
    chk("forbid recognised", classify("never skip GATE HEADINGS") == "forbid")
    chk("rebuke not an order", classify("The fuck are you separating another silo?") == "rebuke")
    chk("chatter not an order", classify("thank you") == "chatter")
    chk("nudge skipped", classify("Your last response did not include a function call or a message. Please use a tool to proceed with the task.") == "skip")
    chk("agent echo skipped", classify("Confirmed: SelfTest.kt references the purged ComposeEmitter") == "skip")
    chk("withdrawal skipped", classify("Never mind for now. Ill come back later") == "skip")

    # watermark: an order at or below the mark must not be re-ingested
    ev = [(10, "t10", "add the gatekeeper"), (20, "t20", "build the pulse")]
    o1, m1 = build("c1", ev, {"conversation": "c1", "last_index": -1})
    o2, m2 = build("c1", ev, m1["mark"])
    chk("first ingest takes both", len(o1) == 2)
    chk("second ingest takes none", len(o2) == 0)
    dup = [(1, "t1", "add the gatekeeper"), (2, "t2", "add the gatekeeper")]
    od, _ = build("c9", dup, {"conversation": "c9", "last_index": -1})
    chk("duplicate order collapsed", len(od) == 1)
    day = [(1, "2026-11-19T23:00:00", "build x"), (2, "2026-11-20T01:00:00", "build y")]
    oy, _ = build("c9", day, {"conversation": "c9", "last_index": -1}, since_day="2026-11-20")
    chk("day window filters", len(oy) == 1 and oy[0]["index"] == 2)

    # a new conversation replays from zero
    o3, _ = build("c2", ev, m1["mark"])
    chk("new session replays", len(o3) == 2)

    # idempotent render: same input -> byte-identical block
    b1 = render_orders("c1", o1, m1["occupation"])
    b2 = render_orders("c1", o1, m1["occupation"])
    chk("render is deterministic", b1 == b2)

    # replace, never append
    board = "## ★ OLD\n\nbody\n"
    merged = merge(board, b1)
    merged2 = merge(merged, b2)
    chk("merge replaces", merged.count(BEGIN) == 1 and merged == merged2)

    # occupation follows the pulse, not a guess
    chk("rest phase detected", occupation({"gapHours": 9.0, "currentPhase": "rest/digest/restore"})["state"] == "returning-from-rest")
    chk("engaged detected", occupation({"gapHours": 0.1, "currentPhase": "wake/active"})["state"] == "engaged")

    # a propagation order must declare the board laws, not leave them to a term guess
    oc, _ = build("c1", [(1, "t1", "auto-propagate this to every board")], {"conversation": "c1", "last_index": -1})
    chk("coupling declared", "MUST #26" in oc[0]["laws"])
    chk("grace window sane", GRACE_MINUTES > 0)
    chk("coupling deterministic", oc[0]["laws"] == build("c1", [(1, "t1", "auto-propagate this to every board")], {"conversation": "c1", "last_index": -1})[0][0]["laws"])

    print(f"chat_gatekeeper selftest: {'ok' if ok else 'BROKEN'}")
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--since", default=None,
                    help="ingest only prompts on/after this day (YYYY-MM-DD); default: today's session day")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    return run(write=a.write, since_day=a.since)


