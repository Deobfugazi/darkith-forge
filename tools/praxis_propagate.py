#!/usr/bin/env python3
"""praxis_propagate.py — propagate the current directive, and its coupled laws, to every board.

The problem this closes: a directive is inscribed once (in TASKS.md), but the boards that
actually steer work are plural — the durable core board, one ephemeral board per live agent
tab, and the board in every other worktree on the box. A worker on a sibling branch that never
receives the directive is not idle, it is working on a superseded order. The Operator must not
be the bus that carries his own directive between his own tabs.

So propagation is derived, not remembered. This tool reads the current directive out of the
durable board, derives the laws coupled to it, and writes that same block into every board it
can find. It is idempotent: a second run with no change writes nothing, which is what makes it
safe to run after every inscription.

What "coupled never" means here, exactly — two derivations, and the receipt keeps them apart:

  DECLARED  the directive section names them itself (`**Coupled never:** NEVER #19, ...`).
            An author who names the law is stating intent; this is the authoritative set.
  DERIVED   laws whose own body in DARKITH.md mentions a term the directive uses. This is
            recall, not judgement: it can only propose, and it is labelled as such in the
            receipt so nobody mistakes a lexical hit for a legal opinion.

The propagated block carries BOTH, but only DECLARED laws are presented as binding. A derived
hit is marked `(derived)` so a reader can tell what the Operator ordered from what a substring
match suggested. Silently promoting a lexical coincidence to a law would be worse than
propagating nothing.

Commands
  (no args)        apply: write the block into every board, then receipt
  --check          gate: fail if any board is stale, if the directive is missing, or if the
                   directive names a law that does not exist
  --receipt        print the last receipt
  --dry-run        show what would change, write nothing
  --targets        list the boards discovered

Exit codes: 0 clean/applied, 1 drift or an unresolvable directive (--check), 2 usage.

SPI-1 (no build): pure stdlib, no network, no Gradle. SPI-2: every read is bytes off disk.
SPI-4: the receipt is the record; stdout is a convenience.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BOARD = ROOT / "TASKS.md"
LAWS = ROOT / "DARKITH.md"
RECEIPT = ROOT / "proof" / "praxis_propagation.json"

# Markers bound the block so re-propagation is a replace, never an append. An append-only
# propagator would grow the board on every run and duplicate the order it carries.
BEGIN = "<!-- PRAXIS:BEGIN — generated by tools/praxis_propagate.py; edit the directive in TASKS.md -->"
END = "<!-- PRAXIS:END -->"

# A directive section is the topmost `## ★` heading: the board's own convention for "this is
# the order in force". Falling back to any `##` heading would propagate an appendix as an order.
DIRECTIVE_HEADING = re.compile(r"^##\s*★\s*(.+?)\s*$", re.MULTILINE)
COUPLED_DECL = re.compile(r"\*\*Coupled (?:never|law)s?:\*\*\s*(.+)", re.IGNORECASE)
LAW_TOKEN = re.compile(r"\b((?:NEVER|MUST|SPI)[-\s]?#?\d+)\b")

# Words too common to couple anything to. Without this, every directive would "derive" every
# law that says "the".
STOP = {
    "the", "and", "for", "that", "this", "with", "from", "must", "never", "spi", "not",
    "are", "was", "has", "have", "its", "all", "any", "one", "two", "own", "our", "his",
    "her", "you", "your", "they", "them", "then", "than", "into", "onto", "over", "under",
    "each", "every", "which", "when", "what", "where", "who", "how", "why", "can", "may",
    "will", "shall", "should", "would", "could", "been", "being", "does", "did", "but",
}


def read_bytes(p: pathlib.Path) -> bytes:
    return p.read_bytes()


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def normalise_law(tok: str) -> str:
    """'NEVER#19', 'never 19', 'SPI-2', 'MUST #35' -> the canonical heading spelling."""
    t = tok.upper().replace("  ", " ").strip()
    m = re.match(r"(NEVER|MUST|SPI)\s*-?\s*#?\s*(\d+)$", t)
    if not m:
        return t
    kind, num = m.group(1), m.group(2)
    return f"SPI-{num}" if kind == "SPI" else f"{kind} #{num}"


def law_corpus() -> dict[str, str]:
    """Law id -> its full body, parsed with law_gate's own regex so there is ONE definition of
    what a law heading looks like. A second parser here would drift from the gate that enforces
    the law, and the two would disagree about the corpus they both claim to describe."""
    sys.path.insert(0, str(ROOT / "tools"))
    import law_gate  # noqa: E402  — deliberate: reuse the gate's regex, do not fork it

    text = LAWS.read_text(encoding="utf-8")
    lines = text.splitlines()
    hits = [(i, m) for i, line in enumerate(lines) for m in [law_gate.LAW.search(line)] if m]
    corpus: dict[str, str] = {}
    for idx, (i, m) in enumerate(hits):
        end = hits[idx + 1][0] if idx + 1 < len(hits) else len(lines)
        corpus[normalise_law(m.group(1))] = "\n".join(lines[i:end])
    return corpus


def directive_section(text: str) -> tuple[str, str] | None:
    """Return (title, body) of the topmost ★ directive section, or None.

    The body stops at the first table row. A directive section in this board is prose followed
    by the task table that carries it out; mirroring the table too would copy every task into
    every worker's board, which is not propagation — it is duplication, and it would make the
    mirror fight the worker's own board for ownership of the same rows.
    """
    m = DIRECTIVE_HEADING.search(text)
    if not m:
        return None
    start = m.end()
    nxt = re.search(r"^##\s", text[start:], re.MULTILINE)
    body = text[start:start + nxt.start()] if nxt else text[start:]
    table = re.search(r"^\s*\|", body, re.MULTILINE)
    if table:
        body = body[:table.start()]
    return m.group(1), body


def declared_laws(body: str) -> list[str]:
    out: list[str] = []
    for line in body.splitlines():
        m = COUPLED_DECL.search(line)
        if not m:
            continue
        for tok in LAW_TOKEN.finditer(m.group(1)):
            n = normalise_law(tok.group(1))
            if n not in out:
                out.append(n)
    return out


def derived_laws(body: str, corpus: dict[str, str], declared: list[str]) -> list[str]:
    """Laws whose body shares DISTINCTIVE terms with the directive. Proposals only.

    A plain word-overlap test is worthless here: measured against this corpus it nominated 38
    of 41 laws, because every law discusses the same project vocabulary. The discriminator has
    to be rarity. A term is kept only when it appears in at most RARE_MAX laws, and a law is
    nominated only when it shares at least RARE_HITS such terms. Those two thresholds are what
    turn "mentions the project" into "is about this specific thing".
    """
    terms = {
        w.lower() for w in re.findall(r"[A-Za-z][A-Za-z0-9_-]{3,}", body)
        if w.lower() not in STOP
    }
    if not terms:
        return []

    RARE_MAX = 3   # a term appearing in more laws than this says nothing about which law
    RARE_HITS = 3  # two shared terms is a coincidence; three is a subject

    law_terms = {
        law_id: {w.lower() for w in re.findall(r"[A-Za-z][A-Za-z0-9_-]{3,}", law_body)}
        for law_id, law_body in corpus.items()
    }
    df = {}
    for t in terms:
        df[t] = sum(1 for s in law_terms.values() if t in s)
    rare = {t for t in terms if df[t] <= RARE_MAX}

    out: list[str] = []
    for law_id, s in law_terms.items():
        if law_id in declared:
            continue
        if len(rare & s) >= RARE_HITS:
            out.append(law_id)
    return sorted(out)


def render_block(title: str, body: str, declared: list[str], derived: list[str],
                 corpus: dict[str, str]) -> str:
    """The propagated block. Byte-stable for a given input so idempotence is provable."""
    lines = [BEGIN, f"## ⟐ PRAXIS — order in force (mirrored from TASKS.md)", ""]
    lines.append(f"**Directive:** {title}")
    lines.append("")
    # Strip ownership markers before quoting. A block-quoted marker pair is still a marker
    # pair: quoting CHAT-GATE:BEGIN/END into this block made a second owner of the same region,
    # and each propagation pass then found two more copies of it. Markers are addresses, not
    # content — they do not survive being quoted.
    quoted = [ln for ln in body.strip("\n").splitlines()
              if not ln.strip().startswith(("<!-- CHAT-GATE:", "<!-- PRAXIS:"))]
    lines += [("> " + ln).rstrip() for ln in quoted]
    lines += ["", f"**Coupled laws (declared by the directive):** "
                  + (", ".join(f"`{l}`" for l in declared) if declared else "_none declared_"), ""]
    if declared:
        lines.append("| law | heading |")
        lines.append("|---|---|")
        for law_id in declared:
            head = corpus.get(law_id, "")
            first = head.splitlines()[0] if head else ""
            m = re.search(r"───\s*.*?\s*(?:\(([^)]*)\))?\s*───", first)
            title_txt = (m.group(1) if m and m.group(1) else "—") if first else "**NOT FOUND IN DARKITH.md**"
            lines.append(f"| `{law_id}` | {title_txt} |")
        lines.append("")
    if derived:
        lines.append(f"**Also matched by term (derived, advisory — not an order):** "
                      + ", ".join(f"`{l}`" for l in derived))
        lines.append("")
    lines += [END, ""]
    return "\n".join(lines)


def strip_block(text: str) -> str:
    """Remove any previously propagated block AND the blank separator it was inserted with.

    Both halves must be exact or `merge` is not idempotent: leaving the separator behind means
    every run adds one blank line, which is an append bug wearing a different coat. Measured:
    before this, a second run grew the board 25275 -> 25276 B.
    """
    while True:
        b = text.find(BEGIN)
        if b < 0:
            break
        e = text.find(END, b)
        if e < 0:  # truncated block: drop to EOF rather than leave an unterminated marker
            return text[:b].rstrip("\n") + "\n"
        e += len(END)
        tail = text[e:].lstrip("\n")
        text = text[:b].rstrip("\n") + "\n\n" + tail
    # collapse any run of blank lines left where the block used to be, so the authored
    # board comes back byte-identical to what it was before propagation
    return re.sub(r"\n{3,}", "\n\n", text)


def merge(board_text: str, block: str) -> str:
    """Insert `block` after the title line, separated by exactly one blank line each side.

    Invariant: merge() and strip_block() are exact inverses, so `strip(merge(x)) == x`. Both
    halves are asserted below by the idempotence check in --check; a one-byte drift per run is
    an append bug and would grow the board forever.
    """
    base = strip_block(board_text)
    lines = base.splitlines()
    insert_at = 0
    for i, ln in enumerate(lines):
        if ln.startswith("# "):
            insert_at = i + 1
            break
    head = lines[:insert_at]
    rest = lines[insert_at:]
    out = head + ["", block.rstrip("\n")] + rest
    return "\n".join(out).rstrip("\n") + "\n"


def discover_targets() -> list[tuple[str, pathlib.Path]]:
    """Every board that can steer work. Read off disk, never assumed to exist."""
    targets: list[tuple[str, pathlib.Path]] = [("durable", BOARD)]

    # Ephemeral agent boards: one per live conversation. The Operator's own convention is
    # workspace/conversations/<id>/TASKS.json.
    for conv in sorted(pathlib.Path("/workspace/conversations").glob("*/TASKS.json")):
        targets.append((f"session:{conv.parent.name}", conv))
    for conv in sorted(pathlib.Path("/workspace/workspace/conversations").glob("*/TASKS.json")):
        targets.append((f"session:{conv.parent.name}", conv))

    # Sibling worktrees: a branch checked out elsewhere has its own TASKS.md and its own agent.
    try:
        out = subprocess.run(["git", "-C", str(ROOT), "worktree", "list", "--porcelain"],
                             capture_output=True, text=True, timeout=20).stdout
    except Exception:
        out = ""
    for ln in out.splitlines():
        if ln.startswith("worktree "):
            wt = pathlib.Path(ln.split(" ", 1)[1])
            if wt.resolve() != ROOT:
                targets.append((f"worktree:{wt.name}", wt / "TASKS.md"))
    return targets


def write_md(path: pathlib.Path, block: str, dry: bool) -> tuple[str, str]:
    """Returns (status, detail). status in {current, updated, would-update, created, missing}."""
    if not path.exists():
        if dry:
            return "would-create", ""
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(block, encoding="utf-8")
        return "created", ""
    before = path.read_text(encoding="utf-8")
    after = merge(before, block)
    if before == after:
        return "current", ""
    if dry:
        return "would-update", f"{len(before)}->{len(after)} B"
    path.write_text(after, encoding="utf-8")
    return "updated", f"{len(before)}->{len(after)} B"


def write_json_board(path: pathlib.Path, block: str, dry: bool) -> tuple[str, str]:
    """A session board's shape is owned by the task tracker that reads it, not by us.

    Observed on disk: `TASKS.json` is a JSON *list* of task objects. Rewriting that into an
    object to hold a `praxis` key would corrupt the file the tracker reads. So when the board
    is a list we never touch it — we write `PRAXIS.md` beside it instead. Same directory, so
    the worker meets the order in the same place it meets its task list, and its own board
    stays byte-identical.
    """
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:
        return "unreadable", str(exc)[:60]

    if isinstance(data, dict):
        if data.get("praxis") == block:
            return "current", ""
        if dry:
            return "would-update", "praxis key"
        data["praxis"] = block
        path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        return "updated", "praxis key"

    # list (or any other shape): mirror beside it, leave the original untouched
    mirror = path.parent / "PRAXIS.md"
    before = mirror.read_text(encoding="utf-8") if mirror.exists() else None
    if before == block:
        return "current", "mirror"
    if dry:
        return "would-update", "mirror beside board"
    mirror.write_text(block, encoding="utf-8")
    return ("created" if before is None else "updated"), "mirror beside board"


def selftest() -> int:
    """MUST #33 — the gate must prove it can fire AND that it stays silent when it should.

    Every charge this gate makes is "this board is stale". A gate that can only ever say that
    is a crying-wolf gate. So: a positive trial (a stale board is caught) and a negative trial
    (a clean board is not), plus the two structural invariants that make repeated runs safe.
    Runs on in-memory fixtures: no writes, no network, no repo mutation.
    """
    fails: list[str] = []

    def check(name: str, ok: bool) -> None:
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}")
        if not ok:
            fails.append(name)

    board = "# BOARD\n\nintro prose\n\n## ★ DIRECTIVE X\n\nbody text here\n\n**Coupled laws:** SPI-29\n"
    title, body = directive_section(board)
    corpus = {"SPI-29": "─── SPI-29 (ORDER TRAVELS) ───\nGATE: tools/praxis_propagate.py\n"}
    declared = declared_laws(body)
    block = render_block(title, body, declared, [], corpus)

    # --- invariants: strip and merge are exact inverses, and merge is idempotent
    check("strip(merge(x)) == x  (round-trip restores authored bytes)", strip_block(merge(board, block)) == board)
    once = merge(board, block)
    check("merge(merge(x)) == merge(x)  (idempotent, no append growth)", merge(once, block) == once)

    # --- negative trial: a clean board must NOT be reported stale
    check("NEGATIVE: clean board reports 'current'", merge(board, block) == once)

    # --- positive trial: a board missing the block MUST be reported stale
    check("POSITIVE: bare board differs from propagated board", merge(board, block) != board)

    # --- sensitivity: a directive with no declared laws must be refused, not guessed
    check("SENSITIVITY: no declaration -> declared_laws() empty", declared_laws("just prose\n") == [])

    # --- specificity: a declaration is parsed, not invented
    check("SPECIFICITY: declaration parsed exactly", declared == ["SPI-29"])

    # --- a declared law with no heading is unresolvable (the order is broken, fail closed)
    check("missing law detected", [l for l in declared if l not in corpus] == [])

    # --- truncated block must not leave an unterminated marker
    trunc = "# B\n\n" + BEGIN + "\n## PRAXIS\nno end marker\n"
    check("truncated block is stripped to EOF", BEGIN not in strip_block(trunc))

    # --- law normalisation accepts the spellings humans actually type
    check("normalise 'never 19' -> 'NEVER #19'", normalise_law("never 19") == "NEVER #19")
    check("normalise 'SPI-2' -> 'SPI-2'", normalise_law("SPI-2") == "SPI-2")

    print(f"praxis selftest: {'PASS' if not fails else 'FAIL'} — "
          f"{10 - len(fails)}/10 trials")
    return 0 if not fails else 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--receipt", action="store_true")
    ap.add_argument("--targets", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()

    if args.selftest:
        return selftest()

    if args.receipt:
        print(RECEIPT.read_text(encoding="utf-8") if RECEIPT.exists()
              else '{"note":"no propagation receipt yet"}')
        return 0

    targets = discover_targets()
    if args.targets:
        for name, p in targets:
            print(f"{name}\t{p}")
        return 0

    if not BOARD.is_file():
        print("praxis: FAIL — no TASKS.md, so there is no directive to propagate")
        return 1

    board_bytes = read_bytes(BOARD)
    text = board_bytes.decode("utf-8")
    found = directive_section(text)
    if not found:
        print("praxis: FAIL — TASKS.md carries no '## ★' directive heading; nothing in force")
        return 1
    title, body = found

    corpus = law_corpus()
    declared = declared_laws(body)
    derived = derived_laws(body, corpus, declared)

    # A directive without a declared coupled-law set cannot be propagated as an order, because
    # the laws are the half of the order that constrains HOW it may be carried out. Deriving
    # them lexically would be this tool inventing law, which is the one thing it must not do.
    if not declared:
        print("praxis: FAIL — the directive declares no coupled laws.")
        print("        Add a line to the directive section in TASKS.md:")
        print("          **Coupled laws:** NEVER #19, MUST #35, MUST #29, SPI-2")
        if derived:
            print(f"        (term match suggests, as a hint only: {', '.join(derived)})")
        print("        The declaration is the order. A derived guess is not.")
        return 1

    # A declared law that does not exist is a broken order, not a formatting nit: the worker
    # would chase a law that no gate enforces. Fail closed, in --check and in apply alike.
    missing = [l for l in declared if l not in corpus]
    if missing:
        print(f"praxis: FAIL — the directive names law(s) absent from DARKITH.md: {missing}")
        return 1

    block = render_block(title, body, declared, derived, corpus)

    # --check must never write. A gate that repairs what it inspects cannot report drift,
    # because it destroys the evidence before judging it.
    dry = args.dry_run or args.check

    results = []
    for name, path in targets:
        try:
            if path.suffix == ".json":
                status, detail = write_json_board(path, block, dry)
            else:
                status, detail = write_md(path, block, dry)
        except Exception as exc:  # a target we cannot write must be named, never skipped
            status, detail = "error", str(exc)[:80]
        results.append({"target": name, "path": str(path), "status": status, "detail": detail})

    stale = [r for r in results if r["status"] not in ("current", "updated", "created")
             or r["status"].startswith("would-")]
    problems = [r for r in results if r["status"] in ("error", "unreadable")]

    receipt = {
        "directive": title,
        "directive_sha256": sha(body.strip().encode("utf-8")),
        "board_sha256": sha(board_bytes),
        "laws": {"declared": declared, "derived_advisory": derived},
        "targets": results,
        "mode": "check" if args.check else ("dry-run" if args.dry_run else "apply"),
        "stale": len(stale),
        "problems": len(problems),
    }

    if not args.dry_run:
        RECEIPT.parent.mkdir(parents=True, exist_ok=True)
        RECEIPT.write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")

    for r in results:
        mark = {"current": "=", "updated": "+", "created": "*"}.get(r["status"], "!")
        print(f"  [{mark}] {r['target']:<28} {r['status']:<12} {r['detail']}")
    print(f"  directive: {title[:60]}")
    print(f"  laws declared: {declared or 'none'} | derived (advisory): {derived or 'none'}")

    if problems:
        print(f"praxis: FAIL — {len(problems)} board(s) could not be read or written")
        return 1
    if args.check and stale:
        print(f"praxis: FAIL — {len(stale)} board(s) do not carry the order in force")
        print("        run tools/praxis_propagate.py to synchronise them")
        return 1
    print(f"praxis: PASS — {len(results)} board(s) agree on the order in force"
          + (" (dry run, nothing written)" if args.dry_run else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
