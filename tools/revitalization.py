TOPOLOGY_HUBS = ("tools/ci.sh", "build.sh", "TASKS.md", "DARKITH.md")


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def is_exempt(path: str) -> bool:
    """The cycle's own output is never unexplained drift. Handles the git porcelain
    truncation: a wholly untracked `proof/` reports as `?? proof/`, an ancestor of
    the exempt prefix."""
    return bool(path) and (path == DRIFT_EXEMPT_PREFIX.rstrip("/")
                           or path.startswith(DRIFT_EXEMPT_PREFIX)
                           or (DRIFT_EXEMPT_PREFIX.rstrip("/") + "/")
                           .startswith(path.rstrip("/") + "/"))


def canonical(obj) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"))


def chash(obj) -> str:
    return sha(canonical(obj).encode("utf-8"))


def now_utc() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def git(root: pathlib.Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=str(root), capture_output=True,
                          text=True, check=False)


def read_receipt(path: pathlib.Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


# =========================================================================== #
#  The pipeline                                                               #
# =========================================================================== #
class Pipeline:
    """One serial S01->S16 pass. Each stage's receipt hash is the next stage's entry
    condition (I1); receipts are content-hash keyed (I7)."""

    def __init__(self, root: pathlib.Path, probes=None, operator="agent",
                 prev_dir=None):
        self.root = root
        self.rev = root / "proof" / "revitalization"
        self.registry_path = self.rev / "probe_registry.json"
        self.rules_path = self.rev / "trace_rules.json"
        self.plan_path = self.rev / "repair_plan.json"
        self.operator = operator
        self.probes = probes
        self.prev_dir = prev_dir
        self.parent = GENESIS
        self.cycle = (now_utc().replace("-", "").replace(":", "")
                      + f"{int(time.time() * 1000) % 1000:03d}")
        self.cycle_dir = self.rev / self.cycle
        self.receipts: dict = {}
        self.reused = 0

    # ---------------------------------------------------------- emit (I1/I3/I7)
    def receipt_path(self, stage_id: str) -> pathlib.Path:
        return self.cycle_dir / f"{stage_id}_{STAGE_NAMES[stage_id]}.json"

    def emit(self, stage_id: str, status: str, input_obj, details=None,
             evidence=None, reason=None, uncertainty=None) -> dict:
        if status not in STATES:
            raise ValueError(f"{stage_id}: illegal state {status!r} (I3)")
        input_sha = chash({"stage": stage_id, "parent": self.parent,
                           "input": input_obj})
        path = self.receipt_path(stage_id)
        if path.is_file():
            old = read_receipt(path)
            if (old.get("input_sha256") == input_sha
                    and old.get("parent_receipt_sha256") == self.parent
                    and old.get("status") == status):
                self.reused += 1
                self.parent = old["receipt_sha256"]
                self.receipts[stage_id] = old
                return old
        rec = {
            "repo": self.root.name,
            "cycle_id": self.cycle,
            "stage_id": stage_id,
            "stage_name": STAGE_NAMES[stage_id],
            "parent_receipt_sha256": self.parent,
            "input_sha256": input_sha,
            "status": status,
            "reason": reason,
            "details": details or {},
            "evidence": evidence or [],
            "uncertainty": uncertainty or [],
            "written_at_utc": now_utc(),
            "operator": self.operator,
        }
        rec["receipt_sha256"] = chash({k: v for k, v in rec.items()
                                       if k != "receipt_sha256"})
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(canonical(rec) + "\n", encoding="utf-8")
        self.parent = rec["receipt_sha256"]
        self.receipts[stage_id] = rec
        print(f"  {stage_id} {STAGE_NAMES[stage_id]:<14} {status}"
              + (f" - {reason}" if reason else ""))
        return rec

    # ---------------------------------------------------------------- S01..S03
    def s1_baseline(self) -> dict:
        commit = git(self.root, "rev-parse", "HEAD").stdout.strip()
        branch = git(self.root, "rev-parse", "--abbrev-ref", "HEAD").stdout.strip()
        dirty = [ln for ln in git(self.root, "status", "--porcelain")
                 .stdout.splitlines() if ln.strip()]
        governing = {p: sha((self.root / p).read_bytes())
                     for p in GOVERNING_SOURCES if (self.root / p).is_file()}
        repo_dirty = [d for d in dirty if not is_exempt(d)]
        input_obj = {"branch": branch, "commit": commit,
                     "dirty_count": len(repo_dirty), "governing": governing}
        details = {"branch": branch, "commit": commit,
                   "dirty_inventory": dirty, "governing": governing}
        return self.emit("S01", "PASS", input_obj, details,
                         evidence=[p for p in GOVERNING_SOURCES
                                   if (self.root / p).is_file()])

    @staticmethod
    def classify(path: str) -> str:
        if path.startswith(("proof/", "docs/evidence/")):
            return "L5"
        if path.startswith("tools/generated/") or path.startswith("build/gen/"):
            return "L4"
        if path in ("DARKITH.md", "RESUME.md") or path.endswith(
                ("STALL_BUDGET.json", "DEFICITS.json")):
            return "L6"
        if path.startswith(("AGENTS.md", "TASKS.md", "README", "docs/")):
            return "L6"
        if path.startswith(("tools/", "build/", "kit/", "nodal/")):
            return "L1"
        if path.startswith(("app/src/main/java/", "omega-app/src/main/java/")):
            return "L2"
        if path.endswith(".html") or path.startswith("app/src/main/assets/"):
            return "L3"
        return "UNKNOWN"

    def s2_inventory(self) -> dict:
        tracked = [ln for ln in git(self.root, "ls-files").stdout.split() if ln]
        registry = {p: self.classify(p) for p in tracked}
        unknown = sorted(p for p, layer in registry.items() if layer == "UNKNOWN")
        counts = {}
        for layer in registry.values():
            counts[layer] = counts.get(layer, 0) + 1
        input_obj = {"tracked": len(tracked), "counts": counts}
        return self.emit("S02", "PASS", input_obj,
                         {"layers": LAYERS, "counts": counts, "unknown": unknown},
                         uncertainty=[f"UNKNOWN classification: {p}"
                                      for p in unknown[:50]])

    def s3_topology(self) -> dict:
        edges = [{"from": a, "to": b, "kind": k, "why": w}
                 for a, b, k, w in DECLARED_EDGES]
        hubs = {h: self.classify(h) for h in TOPOLOGY_HUBS
                if (self.root / h).is_file()}
        unknown = self.receipts["S02"]["details"].get("unknown", [])
        unknown_links = [f"{p} (layer UNKNOWN: no declared edge names it)"
                         for p in unknown[:25]]
        input_obj = {"edges": edges, "hubs": hubs}
        details = {"edges": edges, "hubs": hubs, "unknown_links": unknown_links}
        return self.emit("S03", "PASS", input_obj, details,
                         uncertainty=unknown_links)

    # ---------------------------------------------------------------- S04..S09
    def load_probes(self) -> list:
        if self.probes is not None:
            return self.probes
        if self.registry_path.is_file():
            data = json.loads(self.registry_path.read_text(encoding="utf-8"))
            return data.get("probes", [])
        return [dict(p) for p in BUILTIN_PROBES]

    def run_probe(self, cmd: str) -> dict:
        t0 = time.monotonic()
        try:
            cp = subprocess.run(shlex.split(cmd), cwd=str(self.root),
                                capture_output=True, text=True, timeout=600)
            rc = cp.returncode
            tail = (cp.stdout + cp.stderr)[-4000:]
            state = "PASS" if rc == 0 else ("SKIP" if rc == 3 else "FAIL")
            reason = None if rc == 0 else f"exit {rc}"
        except FileNotFoundError as exc:
            rc, tail, reason, state = None, "", f"runtime absent: {exc}", "SKIP"
        return {"probe": None, "cmd": cmd, "exit": rc,
                "duration_s": round(time.monotonic() - t0, 3),
                "state": state, "reason": reason, "tail": tail}

    def s4_diagnostic(self) -> tuple:
        probes = self.load_probes()
        results = []
        for probe in probes:
            res = self.run_probe(probe["cmd"])
            res["probe"] = probe["name"]
            results.append(res)
        registry_sha = (sha(self.registry_path.read_bytes())
                        if self.registry_path.is_file() else "builtin")
        input_obj = {"registry_sha256": registry_sha,
                     "results": [{"probe": r["probe"], "exit": r["exit"],
                                  "state": r["state"]} for r in results]}
        if not results:
            rec = self.emit("S04", "FAIL", input_obj, {"probes": results},
                            reason="empty probe corpus is not a pass (SPI-32)")
            return rec, results
        rec = self.emit("S04", "PASS", input_obj, {"probes": results})
        return rec, results

    def s5_classify(self, results) -> tuple:
        ledger = [{"probe": r["probe"], "state": r["state"],
                   "evidence": f"S04[{r['probe']}].exit={r['exit']}",
                   "confidence": "measured"} for r in results]
        bad = [row for row, r in zip(ledger, results)
               if not ((r["exit"] == 0 and row["state"] == "PASS")
                       or (r["exit"] == 3 and row["state"] == "SKIP")
                       or ((r["exit"] is None or r["exit"] not in (0, 3))
                           and row["state"] == "FAIL"))]
        input_obj = {"ledger": ledger,
                     "s04_exits": {r["probe"]: r["exit"] for r in results}}
        status = "FAIL" if bad else "PASS"
        rec = self.emit("S05", status, input_obj,
                        {"ledger": ledger, "misstated": bad},
                        reason=(f"{len(bad)} ledger row(s) misstate their probe"
                                if bad else None))
        return rec, bad

    def s6_trace(self, results) -> tuple:
        rules = self.trace_rules()
        defects = []
        for r in results:
            if r["state"] != "FAIL":
                continue
            rule = rules.get(r["probe"], {})
            defects.append({
                "id": f"DEF-{len(defects) + 1:03d}",
                "probe": r["probe"],
                "root_cause": rule.get("root_cause", "UNCONFIRMED"),
                "origin": "origin" if rule.get("root_cause") else "propagated",
                "governing_file": rule.get("governing_file",
                                           self.tool_of(r["cmd"]) or "UNCONFIRMED"),
            })
        names = [d["probe"] for d in defects]
        input_obj = {"defect_signatures": [[d["probe"], d["governing_file"]]
                                           for d in defects],
                     "probe_states": {r["probe"]: r["state"] for r in results}}
        rec = self.emit("S06", "PASS", input_obj, {"defects": defects},
                        reason=(f"{len(defects)} defect(s): {', '.join(names)}"
                                if defects else None))
        return rec, defects

    @staticmethod
    def tool_of(cmd: str):
        m = re.search(r"tools/[\w./-]+\.(?:py|sh|mjs|js)", cmd or "")
        return m.group(0) if m else None

    def trace_rules(self) -> dict:
        if self.rules_path.is_file():
            return json.loads(self.rules_path.read_text(encoding="utf-8")).get("route", {})
        return {}

    def s7_govern(self, defects) -> dict:
        routes = [{"defect": d["id"], "governing_file": d["governing_file"],
                   "layer": (self.classify(d["governing_file"])
                             if d["governing_file"] not in (None, "UNCONFIRMED")
                             else "UNKNOWN"),
                   "root_cause": d["root_cause"]} for d in defects]
        input_obj = {"routes": routes}
        return self.emit("S07", "PASS", input_obj, {"routes": routes},
                         uncertainty=[f"{g['defect']}: repair boundary "
                                      f"{g['layer']}/{g['root_cause']}"
                                      for g in routes])

    def s8_task(self, defects) -> tuple:
        prev_tasks = self.prev_tasks()
        tasks, seq = [], 0
        for d in defects:
            sig = [d["probe"], d["governing_file"]]
            rule = self.trace_rules().get(d["probe"], {})
            prior = self.match_task(prev_tasks, sig, allow_closed=False)
            seq += 1
            if prior:
                task = {"id": prior["id"], "defects": prior["defects"] + [d["id"]],
                        "signature": sig, "reopened": True,
                        "parent_task": prior.get("parent_task"),
                        "governing_file": d["governing_file"],
                        "baseline_commit": self.receipts["S01"]["details"]["commit"]}
            else:
                closed_prior = self.match_task(prev_tasks, sig, allow_closed=True)
                task = {"id": f"REV-{self.cycle}-{seq:03d}",
                        "defects": [d["id"]], "signature": sig, "reopened": False,
                        "parent_task": rule.get("parent_task")
                        or (closed_prior or {}).get("id"),
                        "governing_file": d["governing_file"],
                        "baseline_commit": self.receipts["S01"]["details"]["commit"]}
            task["acceptance_criteria"] = [
                f"probe '{d['probe']}' returns PASS",
                "S14 reconcile clean (no unexplained drift)",
                "S15 evidence bundle attached to this task id",
            ]
            task["evidence"] = [str(self.receipt_path("S04").relative_to(self.root))]
            tasks.append(task)
        input_obj = {"task_ids": sorted(t["id"] for t in tasks),
                     "reopened": [t["id"] for t in tasks if t["reopened"]]}
        rec = self.emit("S08", "FAIL" if defects else "PASS", input_obj,
                        {"tasks": tasks},
                        reason=(f"{len(tasks)} corrective task(s) open"
                                if defects else None))
        return rec, tasks

    def prev_tasks(self) -> list:
        latest = self.prev_cycle_dir()
        if not latest:
            return []
        f = latest / "S16_BOARD+ROTATE.json"
        if not f.is_file():
            return []
        return read_receipt(f)["details"].get("task_queue", [])

    def prev_cycle_dir(self):
        return self.prev_dir if (self.prev_dir and self.prev_dir.is_dir()) else None

    @staticmethod
    def match_task(prev_tasks, sig, allow_closed: bool):
        for t in prev_tasks:
            if t.get("signature") == list(sig) and (
                    allow_closed or t.get("status") != "closed"):
                return t
        return None

    def s9_authorize(self, tasks) -> tuple:
        plan = self.repair_plan()
        by_task = {r.get("task"): r for r in plan.get("repairs", [])}
        decisions = [{"task": t["id"],
                      "class": by_task.get(t["id"], {})
                      .get("class", "HUMAN_REQUIRED"),
                      "plan_present": t["id"] in by_task}
                     for t in tasks]
        legal = all(d["class"] in ("AUTO_APPROVED", "HUMAN_REQUIRED")
                    for d in decisions)
        if not tasks:
            status, reason = "INACTIVE", "no repairs open this cycle"
        elif legal:
            status = "PASS"
            reason = ("authorization boundary recorded (I10): "
                      + ", ".join(f"{d['task']}={d['class']}" for d in decisions))
        else:
            status, reason = "FAIL", "illegal authorization class in repair plan"
        input_obj = {"decisions": decisions,
                     "plan_sha256": sha(self.plan_path.read_bytes())
                     if self.plan_path.is_file() else "none"}
        return self.emit("S09", status, input_obj, {"decisions": decisions},
                         reason=reason), decisions

    def repair_plan(self) -> dict:
        if self.plan_path.is_file():
            return json.loads(self.plan_path.read_text(encoding="utf-8"))
        return {}


    # ---------------------------------------------------------------- S10..S13
    def s10_repair(self, tasks, decisions) -> tuple:
        plan = self.repair_plan()
        by_task = {r.get("task"): r for r in plan.get("repairs", [])}
        manifest, pending = [], []
        ops = {"regenerate": [], "verify": [], "blast": []}
        for t, d in zip(tasks, decisions):
            r = by_task.get(t["id"])
            if not r or d["class"] != "AUTO_APPROVED":
                pending.append(t["id"])  # autonomous detection, bounded mutation (I10)
                continue
            for edit in r.get("edits", []):
                tgt = self.root / edit["target"]
                if not tgt.is_file():
                    manifest.append({"target": edit["target"], "applied": False,
                                     "why": "target missing"})
                    continue
                before = tgt.read_bytes()
                old, new = edit["old"].encode("utf-8"), edit["new"].encode("utf-8")
                hits = before.count(old)
                if hits != 1:
                    manifest.append({"target": edit["target"], "applied": False,
                                     "why": f"expected exactly one match, found {hits}"})
                    continue
                tgt.write_bytes(before.replace(old, new))
                manifest.append({"target": edit["target"], "applied": True,
                                 "before_sha256": sha(before),
                                 "after_sha256": sha(tgt.read_bytes())})
            for key in ("regenerate", "verify", "blast"):
                ops[key] += [{"task": t["id"], "cmd": c} for c in r.get(key, [])]
        if not tasks:
            rec = self.emit("S10", "INACTIVE", {"manifest": [], "pending": []},
                            {"manifest": [], "pending_human": [],
                             "regenerate": ops["regenerate"],
                             "verify": ops["verify"], "blast": ops["blast"]},
                            reason="no repairs owed this cycle (no defect found)")
            return rec, manifest, ops
        blocked = [m for m in manifest if not m.get("applied")]
        input_obj = {"applied": [m for m in manifest if m.get("applied")],
                     "pending": pending,
                     "regenerate_cmds": [o["cmd"] for o in ops["regenerate"]],
                     "verify_cmds": [o["cmd"] for o in ops["verify"]],
                     "blast_cmds": [o["cmd"] for o in ops["blast"]]}
        rec = self.emit("S10", "FAIL" if blocked else "PASS", input_obj,
                        {"manifest": manifest, "pending_human": pending,
                         "regenerate": ops["regenerate"], "verify": ops["verify"],
                         "blast": ops["blast"], "plan_present": bool(by_task)},
                        evidence=None,
                        reason=(f"{len(blocked)} edit(s) not applied - repair deferred"
                                if blocked else None))
        return rec, manifest, ops

    def run_cmd(self, cmd: str) -> dict:
        try:
            cp = subprocess.run(shlex.split(cmd), cwd=str(self.root),
                                capture_output=True, text=True, timeout=600)
            tail = (cp.stdout + cp.stderr)[-4000:]
            tail_sha = sha(tail.encode("utf-8") or b"ok")
            state = "PASS" if cp.returncode == 0 else \
                ("SKIP" if cp.returncode == 3 else "FAIL")
            return {"exit": cp.returncode, "tail": tail, "tail_sha256": tail_sha,
                    "state": state}
        except FileNotFoundError as exc:
            return {"exit": None, "tail": str(exc), "tail_sha256": "absent",
                    "state": "SKIP"}

    def s11_regenerate(self, ops: dict) -> tuple:
        regenerate = ops.get("regenerate", [])
        if not regenerate:
            return self.emit("S11", "INACTIVE", {"runs": []}, {"runs": []},
                             reason="nothing generated (no source changed this "
                                    "cycle)"), True
        runs, holds = [], True
        for item in regenerate:
            h1 = self.run_cmd(item["cmd"])
            h2 = self.run_cmd(item["cmd"])
            item_holds = (h1["exit"] == 0 and h2["exit"] == 0
                          and h1["tail_sha256"] == h2["tail_sha256"])
            holds = holds and item_holds
            runs.append({"task": item["task"], "cmd": item["cmd"],
                         "exit": h1["exit"], "exit_again": h2["exit"],
                         "output_sha256": h1["tail_sha256"],
                         "again_sha256": h2["tail_sha256"], "holds": item_holds})
        input_obj = {"runs": [{"task": r["task"], "cmd": r["cmd"]} for r in runs]}
        rec = self.emit("S11", "PASS" if holds else "FAIL", input_obj,
                        {"runs": runs},
                        reason=(None if holds else
                                "back-edge fired but did not HOLD: regeneration is "
                                "not idempotent, so S10 reopens (Divergence-5)"))
        return rec, holds

    def s12_verify_local(self, ops: dict, tasks) -> tuple:
        verify_ops = ops.get("verify", [])
        reruns = [{"task": t["id"], "cmd": self.probe_cmd(t["signature"][0])}
                  for t in tasks]
        runs = [{"task": v["task"], "cmd": v["cmd"]} for v in verify_ops] + reruns
        if not runs:
            rec = self.emit("S12", "INACTIVE", {"runs": []}, {"runs": []},
                            reason="no repair to verify this cycle")
            return rec, True
        out, ok = [], True
        for r in runs:
            h = self.run_cmd(r["cmd"])
            ok = ok and h["state"] == "PASS"
            out.append({"task": r["task"], "cmd": r["cmd"], "exit": h["exit"],
                        "state": h["state"], "tail": h["tail"][:600]})
        input_obj = {"runs": [{"task": r["task"], "cmd": r["cmd"]} for r in runs]}
        rec = self.emit("S12", "PASS" if ok else "FAIL", input_obj, {"runs": out},
                        reason=(None if ok else
                                "repaired behavior not demonstrated yet "
                                "(I4: detection is not verification)"))
        return rec, ok

    def probe_cmd(self, name: str) -> str:
        for probe in self.load_probes():
            if probe["name"] == name:
                return probe["cmd"]
        return "python3 -c \"import sys; print('probe %s not in registry'); " \
               "sys.exit(2)\"" % name

    def s13_verify_blast(self, ops: dict, tasks) -> tuple:
        blast_ops = ops.get("blast", [])
        targets = sorted({m["target"] for m
                          in self.receipts["S10"]["details"].get("manifest", [])
                          if m.get("applied")})
        if not tasks and not targets:
            rec = self.emit("S13", "INACTIVE", {"runs": []}, {"runs": []},
                            reason="no repair this cycle")
            return rec, True
        runs, ok, whys = [], True, []
        for item in blast_ops:
            h = self.run_cmd(item["cmd"])
            ok = ok and h["state"] == "PASS"
            runs.append({"task": item["task"], "cmd": item["cmd"],
                         "exit": h["exit"], "state": h["state"],
                         "tail": h["tail"][:600]})
        if targets and not blast_ops:
            whys.append("source changed but no blast-radius command was declared: "
                        + ", ".join(targets))
            ok = False
        for t in targets:
            present = (self.root / t).is_file()
            runs.append({"neighbor": t, "layer": self.classify(t),
                         "state": "PASS" if present else "FAIL",
                         "why": "consumer of a changed node must still resolve"})
            ok = ok and present
        input_obj = {"blast_cmds": [o["cmd"] for o in blast_ops],
                     "targets": targets}
        rec = self.emit("S13", "PASS" if ok else "FAIL", input_obj,
                        {"runs": runs}, reason=("; ".join(whys) or None))
        return rec, ok

    # ---------------------------------------------------------------- S14..S16
    def s14_reconcile(self) -> tuple:
        cp = git(self.root, "status", "--porcelain")
        dirty = [ln[3:].strip().strip('"')
                 for ln in cp.stdout.splitlines() if ln.strip()]
        manifest_targets = {m["target"] for m
                            in self.receipts["S10"]["details"].get("manifest", [])
                            if m.get("applied")}
        dirty_paths = [p.split(" -> ")[0] for p in dirty]
        cycle_output = [p for p in dirty_paths if is_exempt(p)]
        drift = [p for p in dirty_paths
                 if not is_exempt(p) and p not in manifest_targets]
        clean = not drift
        details = {"dirty": dirty, "unexplained_drift": drift,
                   "cycle_output": cycle_output,
                   "manifest_targets": sorted(manifest_targets),
                   "regenerable_trees": [p for p in ("tools/generated", "build/gen")
                                         if (self.root / p).is_dir()],
                   "full_suite": {"executor": "tools/ci.sh",
                                  "receipt": "proof/ci_last.log (regenerates from a "
                                             "fresh run; CI is the executor)"}}
        input_obj = {"dirty": dirty_paths, "drift": drift}
        rec = self.emit("S14", "PASS" if clean else "FAIL", input_obj, details,
                        reason=(None if clean else
                                f"{len(drift)} unexplained dirty path(s): {drift[:4]}"))
        return rec, clean, drift

    def s15_seal(self, tasks, ok_local: bool, ok_blast: bool, clean: bool) -> tuple:
        stage_files = [self.receipt_path(s).name for s in STAGE_IDS
                       if s in self.receipts]
        receipt_ids = [s for s in STAGE_IDS if s in self.receipts]
        sealed = {
            "cycle_id": self.cycle,
            "revision": self.receipts["S01"]["details"]["commit"],
            "changed_files": sorted({m["target"] for m
                                     in self.receipts["S10"]["details"]
                                     .get("manifest", []) if m.get("applied")}),
            "stage_files": stage_files,
            "commands": [{"probe": r["probe"], "cmd": r["cmd"]} for r in
                         self.receipts["S04"]["details"]["probes"]],
            "task_ids": [t["id"] for t in tasks],
            "open_defects": [t["id"] for t in tasks if not self.task_verified(t)],
            "remaining_uncertainty": sorted({u for s in self.receipts
                                             for u in self.receipts[s]
                                             .get("uncertainty", [])})[:40],
        }
        ok = clean and ok_local and ok_blast
        evidence = [str(self.receipt_path(s).relative_to(self.root))
                    for s in receipt_ids]
        input_obj = {"sealed": {k: sealed[k] for k in
                                ("cycle_id", "revision", "changed_files",
                                 "stage_files", "task_ids")}}
        rec = self.emit("S15", "PASS" if ok else "FAIL", input_obj,
                        {"bundle": sealed}, evidence=evidence,
                        reason=(None if ok else
                                "evidence sealed around OPEN defects - closure "
                                "blocked per I8"))
        return rec, ok

    def task_verified(self, task) -> bool:
        return (self.receipts.get("S12", {}).get("status") == "PASS"
                and self.receipts.get("S14", {}).get("status") == "PASS")

    def s16_board_rotate(self, tasks, ok_local, ok_blast, clean, prev_skips) -> tuple:
        skips = [p["probe"] for p in self.receipts["S04"]["details"]["probes"]
                 if p["state"] == "SKIP"]
        newly_skipped = [s for s in skips if s not in prev_skips]
        open_tasks = [t for t in tasks if not self.task_verified(t)]
        task_queue = [dict(t, status=("closed" if self.task_verified(t) else "open"))
                      for t in tasks]
        can_close = (clean and ok_local and ok_blast
                     and not open_tasks and not newly_skipped)
        s16_status = "PASS" if can_close else "FAIL"
        block = self.board_block(can_close, task_queue, skips,
                                 s16_status=s16_status)
        input_obj = {"closed": can_close,
                     "task_ids": sorted(t["id"] for t in tasks),
                     "skip_count": len(skips)}
        rec = self.emit("S16", "PASS" if can_close else "FAIL", input_obj,
                        {"closed": can_close, "task_queue": task_queue,
                         "regression_queue": [],
                         "changed_nodes": sorted({m["target"] for m in
                                                  self.receipts["S10"]["details"]
                                                  .get("manifest", [])
                                                  if m.get("applied")}),
                         "skips": skips, "newly_skipped": newly_skipped,
                         "board_block": block},
                        reason=(None if can_close else closure_reason(
                            open_tasks, newly_skipped, clean, ok_local, ok_blast)))
        return rec, can_close

    def board_block(self, closed: bool, task_queue, skips,
                    s16_status: str = "PASS") -> str:
        status_map = {"PASS": "done", "FAIL": "in_progress", "SKIP": "todo",
                      "INACTIVE": "blocked"}
        lines = [
            f"cycle `{self.cycle}` - verdict: "
            + ("CYCLE CLOSED (all stages evidence-sealed)"
               if closed else "CYCLE OPEN"),
            "",
            "| stage | name | status | receipt |",
            "|---|---|---|---|",
        ]
        for sid, name in STAGES:
            rec = self.receipts.get(sid)
            if rec is None and sid == "S16":
                # S16 cites its own receipt: the path is deterministic even though
                # this receipt is written after the block it contains.
                rel = str(self.receipt_path(sid).relative_to(self.root))
                lines.append(f"| {sid} | {name} | "
                             f"{status_map.get(s16_status, 'todo')} | {rel} |")
                continue
            if rec is None:
                lines.append(f"| {sid} | {name} | todo | MISSING-RECEIPT |")
                continue
            rel = str(self.receipt_path(sid).relative_to(self.root))
            lines.append(f"| {sid} | {name} | {status_map[rec['status']]} | {rel} |")
        if task_queue:
            lines += ["", "Tasks:", ""]
            for t in task_queue:
                tag = "REOPENED" if t.get("reopened") else "new"
                lines.append(f"- **{t['id']}** ({tag}, {t['status']}): probe "
                             f"`{t['signature'][0]}`; governing `{t['governing_file']}`")
        if skips:
            lines += ["", "Named skips this cycle (SKIP is never PASS): "
                      + ", ".join(skips) + "."]
        return "\n".join(lines)


def closure_reason(open_tasks, newly_skipped, clean, ok_local, ok_blast) -> str:
    why = []
    if open_tasks:
        why.append(f"{len(open_tasks)} corrective task(s) open")
    if not clean:
        why.append("S14 reconcile found unexplained drift")
    if not ok_local:
        why.append("S12 local verification failed")
    if not ok_blast:
        why.append("S13 blast verification failed")
    if newly_skipped:
        why.append(f"new SKIP introduced: {', '.join(newly_skipped)}")
    return "closure blocked: " + "; ".join(why)


