ROOT = pathlib.Path(__file__).resolve().parent.parent
REV = ROOT / "proof" / "revitalization"
CURRENT = REV / "CURRENT"
REGISTRY = REV / "probe_registry.json"
TRACE_RULES = REV / "trace_rules.json"
REPAIR_PLAN = REV / "repair_plan.json"
BOARD = ROOT / "TASKS.md"
BOARD_BEGIN = ("<!-- REVITALIZATION:BEGIN - generated by tools/revitalization.py; "
               "edit the cycle, not this block -->")
BOARD_END = "<!-- REVITALIZATION:END -->"

GENESIS = "GENESIS"
STATES = ("PASS", "FAIL", "SKIP", "INACTIVE")
