def selftest() -> int:
    """Runs the pipeline inside throwaway git sandboxes with synthetic probes and
    witnesses: serial chaining (I1), four-state legality (I3), task inheritance (I2),
    failure routing (I6), idempotency (I7), evidence-only closure (I8), and the
    reopen-vs-new-task routing (Divergence-9)."""
    fails: list = []
    ok = True

    def check(name: str, cond: bool, note=""):
        nonlocal ok
        print(f"  {'ok  ' if cond else 'FAIL'} {name}" + (f" - {note}" if note else ""))
        ok = ok and cond
        if not cond:
            fails.append(name)

    def sh(root, cmd):
        subprocess.run(["bash", "-c", cmd], cwd=str(root), check=False,
                       capture_output=True, text=True)

    def commit_all(root, msg):
        sh(root, "git add -A && git -c user.email=a@a -c user.name=a commit -q -m '%s'"
           % msg)

    def sandbox(name: str) -> pathlib.Path:
        root = pathlib.Path(tempfile.mkdtemp(prefix="revital-" + name + "-"))
        (root / "tools").mkdir()
        (root / "proof").mkdir()
        (root / "README.md").write_text("sandbox\n")
        sh(root, "git init -q")
        commit_all(root, "seed")
        return root

    def registry(root, probes):
        d = root / "proof" / "revitalization"
        d.mkdir(exist_ok=True)
        (d / "probe_registry.json").write_text(
            json.dumps({"probes": probes}, indent=1))

    def current_cycle(root) -> str:
        return json.loads((root / "proof/revitalization/CURRENT")
                          .read_text(encoding="utf-8"))["cycle_id"]

    def receipt(root, cycle, name):
        return read_receipt(root / "proof/revitalization" / cycle / name)

    print("== sandbox 1: clean tree, probe passes -> cycle closes ==")
    r1 = sandbox("clean")
    registry(r1, [{"name": "p-ok", "cmd": "python3 -c \"print('pass-here')\""}])
    rc1 = command_run(r1)
    check("clean cycle exits 0 (closed)", rc1 == 0, f"got {rc1}")
    g1, f1 = verify_chain(r1)
    check("gate PASSes the clean sealed chain", g1 == 0, "; ".join(f1))
    cyc1 = current_cycle(r1)
    s16 = receipt(r1, cyc1, "S16_BOARD+ROTATE.json")
    check("S16 records the cycle as closed", s16["details"]["closed"] is True)
    block = s16["details"]["board_block"]
    check("S16 board block seals 16 staged rows",
          all(f"| {sid} " in block for sid in STAGE_IDS)
          and block.count("proof/revitalization") == 16)

    print("== sandbox 2: idempotency (I7) ==")
    rc2 = command_run(r1)
    check("re-running a closed cycle is a no-op exit 0", rc2 == 0, f"got {rc2}")
    dirs = [p.name for p in (r1 / "proof/revitalization").iterdir() if p.is_dir()]
    check("no duplicate cycle dir was created (I7)", len(dirs) == 1, str(dirs))

    print("== sandbox 3: failing probe -> defect + task (I6); SKIP never PASS (I3) ==")
    r3 = sandbox("failing")
    registry(r3, [
        {"name": "p-bad", "cmd": "python3 -c \"import sys; sys.exit(2)\""},
        {"name": "p-skip", "cmd": "python3 -c \"import sys; sys.exit(3)\""},
    ])
    rc3 = command_run(r3)
    check("defect cycle exits 1 (failure is loud, I6)", rc3 == 1, f"got {rc3}")
    cyc3 = current_cycle(r3)
    s05 = receipt(r3, cyc3, "S05_CLASSIFY.json")
    states = {row["probe"]: row["state"] for row in s05["details"]["ledger"]}
    check("failing probe classified FAIL (I3)", states.get("p-bad") == "FAIL",
          str(states))
    check("exit-3 probe classified SKIP, never PASS (I3)",
          states.get("p-skip") == "SKIP", str(states))
    s08 = receipt(r3, cyc3, "S08_TASK.json")
    t_first = s08["details"]["tasks"][0]
    check("task carries defect + governing + commit + evidence (I2)",
          bool(t_first["defects"] and t_first["governing_file"]
               and t_first["baseline_commit"] and t_first["evidence"]
               and t_first["acceptance_criteria"]))
    s16_open = receipt(r3, cyc3, "S16_BOARD+ROTATE.json")
    check("cycle refuses closure while a task is open (I8)",
          s16_open["details"]["closed"] is False and s16_open["status"] == "FAIL")
    g3, f3 = verify_chain(r3)
    check("gate PASSes an honest OPEN chain", g3 == 0, "; ".join(f3))

    print("== sandbox 4: same-baseline rerun with open tasks defers (I1/I7) ==")
    rc4 = command_run(r3)
    check("open-mandate rerun defers with exit 2 (never waits, never skips)",
          rc4 == 2, f"got {rc4}")

    print("== sandbox 5: tamper detection ==")
    s08_path = r3 / "proof/revitalization" / cyc3 / "S08_TASK.json"
    forged08 = read_receipt(s08_path)
    forged08["status"] = "PASS"  # bit-flip a FAIL into a claimed PASS, no rehash
    s08_path.write_text(canonical(forged08) + "\n", encoding="utf-8")
    g5, f5 = verify_chain(r3)
    check("a bit-flipped FAIL->PASS receipt is detected", g5 == 1 and bool(f5),
          "; ".join(f5))
    # Rehash the SAME forgery so its own checksum is internally valid: the chain
    # must STILL reject it, because S09's parent field pins the original bytes.
    forged05 = read_receipt(s08_path)
    forged05["receipt_sha256"] = chash(
        {k: v for k, v in forged05.items() if k != "receipt_sha256"})
    s08_path.write_text(canonical(forged05) + "\n", encoding="utf-8")
    g5c, f5c = verify_chain(r3)
    check("even a rehashed forgery is rejected by the parent binding",
          g5c == 1 and any("parent" in f for f in f5c), "; ".join(f5c))
    s08_path.unlink()
    g5b, f5b = verify_chain(r3)
    check("a gap in the serial chain is detected (I1)", g5b == 1
          and any("gap" in f for f in f5b), "; ".join(f5b))

    print("== sandbox 6: no chain -> named SKIP (never pass) ==")
    r6 = sandbox("empty")
    g6, _ = verify_chain(r6)
    check("no receipts -> named SKIP (exit 3)", g6 == 3)

    print("== sandbox 7: S10 executes only AUTO_APPROVED repairs (I10) ==")
    r7 = sandbox("auth")
    registry(r7, [{"name": "p-bad", "cmd": "python3 -c \"import sys; sys.exit("
                   "0 if 'fixed' in open('repairable.txt').read() else 2)\""}])
    (r7 / "repairable.txt").write_text("block-a\n")
    commit_all(r7, "add repairable")
    plan_dir = r7 / "proof/revitalization"
    plan_dir.mkdir(exist_ok=True)
    (plan_dir / "repair_plan.json").write_text(json.dumps({
        "_law": "I10 - detection autonomous, mutation bounded",
        "repairs": [
            {"task": "ANY", "class": "AUTO_APPROVED",
             "edits": [{"target": "repairable.txt",
                        "old": "block-a", "new": "fixed"}],
             "regenerate": ["python3 -c \"print('regen')\""],
             "verify": ["python3 -c \"print('verified')\""],
             "blast": []},
        ]}, indent=1))
    # S09 defaults to HUMAN_REQUIRED (the plan does not name the task id), so S10
    # must NOT apply the edit: detection is autonomous, mutation is bounded.
    rc7 = command_run(r7)
    cyc7 = current_cycle(r7)
    s10 = receipt(r7, cyc7, "S10_REPAIR.json")
    check("HUMAN_REQUIRED repair is NOT applied under I10",
          rc7 == 1 and s10["details"]["pending_human"]
          and not [m for m in s10["details"]["manifest"] if m.get("applied")],
          str(s10["details"]))
    check("bounded mutation: target untouched without authorization",
          (r7 / "repairable.txt").read_text() == "block-a\n")

    # Authorized path: name the actual task id, class AUTO_APPROVED -> S10 applies,
    # S11/S12 hold, S14 sees only the sanctioned edit, S16 can close.
    s08 = receipt(r7, cyc7, "S08_TASK.json")
    real_id = s08["details"]["tasks"][0]["id"]
    (plan_dir / "repair_plan.json").write_text(json.dumps({
        "repairs": [
            {"task": real_id, "class": "AUTO_APPROVED",
             "edits": [{"target": "repairable.txt",
                        "old": "block-a", "new": "fixed"}],
             "regenerate": ["python3 -c \"print('regen-1')\""],
             "verify": ["python3 -c \"print('verified')\""],
             "blast": ["python3 -c \"print('blast-ok')\""]},
        ]}, indent=1))
    # baseline changed (plan written + work pending) so the cycle is not a no-op:
    # drift is expected, so repair under authorization runs on the same cycle.
    rc8 = command_run(r7)
    check("AUTO_APPROVED repair executes end-to-end (exit 0)",
          rc8 == 0, f"got {rc8}")
    check("the authorized edit actually landed (root-level file changed)",
          (r7 / "repairable.txt").read_text() == "fixed\n")
    cyc8 = current_cycle(r7)
    s08b = receipt(r7, cyc8, "S08_TASK.json")
    check("same signature REOPENS the original task, never duplicates it (I9)",
          s08b["details"]["tasks"] and s08b["details"]["tasks"][0]["reopened"]
          is True and s08b["details"]["tasks"][0]["id"] == real_id,
          str([t["id"] for t in s08b["details"]["tasks"]]))
    g8, f8 = verify_chain(r7)
    check("gate PASSes the repaired+sealed chain", g8 == 0, "; ".join(f8))

    print()
    if ok:
        print("REVITALIZATION SELF-TEST: PASS (every invariant witnessed)")
        return 0
    print(f"REVITALIZATION SELF-TEST: FAIL ({len(fails)}): {fails}")
    return 1


def main(argv: list) -> int:
    ap = argparse.ArgumentParser(
        description="sixteen-stage serial corrective cycle (I1-I10)")
    ap.add_argument("command", nargs="?", default="gate",
                    choices=("run", "gate", "selftest", "write-board"))
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--operator", default="agent")
    args = ap.parse_args(argv[1:])
    if args.command == "selftest":
        return selftest()
    if args.command == "run":
        return command_run(ROOT, operator=args.operator)
    if args.command == "gate":
        return command_gate(ROOT, as_json=args.json)
    if args.command == "write-board":
        return command_write_board(ROOT)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
