#!/usr/bin/env python3
"""revitalization.py - the sixteen-stage serial corrective cycle (I1-I10), as ONE apparatus.

Why this exists: the Operator converged every prior variant of the diagnostic/repair
flow (7-step, 10-step, 16-step, 20-step spellings of the same cycle) on a fixed
point - sixteen stages, each of which consumes the previous stage's VERIFIED
receipt as its literal entry condition. The invariant is not the step count; it is
the chain of evidence-bound receipts:

    S01 BASELINE -> S02 INVENTORY -> S03 TOPOLOGY -> S04 DIAGNOSTIC -> S05 CLASSIFY
    -> S06 TRACE -> S07 GOVERN -> S08 TASK -> S09 AUTHORIZE -> S10 REPAIR
    -> S11 REGENERATE -> S12 VERIFY-LOCAL -> S13 VERIFY-BLAST -> S14 RECONCILE
    -> S15 SEAL -> S16 BOARD+ROTATE

The ten invariants, each enforced by a named check below (never a note):

  I1  serial dependency      S(n+1) exists only as a child of S(n)'s receipt hash;
                             a missing predecessor DEFERS (exit 2), never waits, never skips.
  I2  evidence inheritance   every task carries originating defect, parent task,
                             governing clause, baseline commit, evidence refs.
  I3  four-state integrity   PASS / FAIL / SKIP / INACTIVE only; SKIP is never PASS;
                             missing evidence is never PASS; INACTIVE never implies
                             healthy (the gate cross-checks S05 against S04 exit codes).
  I4  repair integrity chain detection != correction != verification != closure.
  I5  root-level repair      S10 touches source/generator/config only; generated
                             tissue is regenerated (S11), never hand-patched.
  I6  failure routing        a FAIL auto-creates or reopens a corrective task; open
                             tasks block closure. Failure is loud (exit 1).
  I7  idempotency            receipt identity is content-hash keyed (baseline hash +
                             registry hash), not status-flag keyed; re-running a
                             completed cycle duplicates nothing (exit 0 no-op), and a
                             cycle whose tasks are still open defers (exit 2).
  I8  evidence-only closure  a cycle/task closes only when acceptance criteria are
                             verified AND the sealed bundle names every task.
  I9  temporal integrity     every receipt carries written_at_utc; recurring drift
                             REOPENS its task (a new proof), never a status flip.
  I10 authorization boundary detection and task generation are autonomous; S10 applies
                             only AUTO_APPROVED-class repairs; HUMAN_REQUIRED repairs
                             are recorded pending and left to the worker.

Receipts live under `proof/revitalization/<cycle>/Sxx_NAME.json` and are committed as
evidence. `proof/revitalization/CURRENT` (plain JSON, no symlink: Termux reads it)
names the latest cycle. A CI run WRITES NOTHING (I7): CI only verifies (subcommand
`gate`). The probe registry `proof/revitalization/probe_registry.json` (optional)
overrides the builtin probe set; `trace_rules.json` routes probe -> governing clause;
`repair_plan.json` carries operator-authorized repairs for S10.

Usage:
    python3 tools/revitalization.py selftest      # sandbox proof of every invariant
    python3 tools/revitalization.py run           # execute one cycle (writes receipts)
    python3 tools/revitalization.py gate          # verify the sealed chain (CI; read-only)
    python3 tools/revitalization.py write-board   # paste the sealed cycle onto TASKS.md
    python3 tools/revitalization.py --json        # machine-readable summary

Exit codes (run): 0 cycle closed clean | 1 defects found, tasks open | 2 deferred
(upstream stale / previous cycle's tasks open).  Gate: 0 chain sound | 1 violation |
3 no receipts yet.
"""
