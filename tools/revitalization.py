def idempotency_key(root: pathlib.Path) -> dict:
    """Content-hash keyed, not status-flag keyed (I7). The cycle's own output
    (proof/revitalization/**) is excluded: receipts are the WORK PRODUCT, and a key
    that counted its own evidence would never repeat. The repair plan and trace
    rules are inputs to the cycle, so their content hashes belong in the key."""
    def sha_of(path: pathlib.Path) -> str:
        return sha(path.read_bytes()) if path.is_file() else "none"
    commit = git(root, "rev-parse", "HEAD").stdout.strip()
    branch = git(root, "rev-parse", "--abbrev-ref", "HEAD").stdout.strip()
    dirty = [ln[3:].strip().strip('"').split(" -> ")[0]
             for ln in git(root, "status", "--porcelain").stdout.splitlines()
             if ln.strip()]
    repo_dirty = sorted(p for p in dirty if not is_exempt(p))
    governing = {p: sha((root / p).read_bytes()) for p in GOVERNING_SOURCES
                 if (root / p).is_file()}
    return {"branch": branch, "commit": commit, "dirty": repo_dirty,
            "governing": governing,
            "registry_sha256": sha_of(root / "proof/revitalization/probe_registry.json"),
            "trace_rules_sha256": sha_of(root / "proof/revitalization/trace_rules.json"),
            "plan_sha256": sha_of(root / "proof/revitalization/repair_plan.json")}


def command_run(root: pathlib.Path, operator="agent") -> int:
    key = idempotency_key(root)
    rev = root / "proof" / "revitalization"
    marker = rev / "CURRENT"
    prev_dir, prev_skips, prev_marker = None, [], None
    if marker.is_file():
        try:
            prev = json.loads(marker.read_text(encoding="utf-8"))
        except ValueError:
            prev = None
        if prev and prev.get("idempotency_key") == key:
            if prev.get("closed"):
                print(f" revitalization: idempotent no-op (I7) - cycle "
                      f"{prev.get('cycle_id')} already closed on this exact content "
                      f"hash; nothing to duplicate.")
                return 0
            print(f" revitalization: UPSTREAM_STALE (I1/I7) - cycle "
                  f"{prev.get('cycle_id')} is not closed and its open task(s) hold "
                  f"the mandate; deferring to the next tick. exit 2")
            return 2
        if prev and prev.get("cycle_id") and (rev / str(prev["cycle_id"])).is_dir():
            prev_dir = rev / str(prev["cycle_id"])
            f = prev_dir / "S16_BOARD+ROTATE.json"
            if f.is_file():
                prev_skips = read_receipt(f)["details"].get("skips", [])
            prev_marker = prev
    p = Pipeline(root, operator=operator, prev_dir=prev_dir)
    rev.mkdir(parents=True, exist_ok=True)
    print(f"=== revitalization cycle {p.cycle} ===")
    marker.write_text(canonical(
        {"cycle_id": p.cycle, "closed": False, "idempotency_key": key,
         "written_at_utc": now_utc()}) + "\n", encoding="utf-8")
    p.s1_baseline()
    p.s2_inventory()
    p.s3_topology()
    _, results = p.s4_diagnostic()
    _, _bad = p.s5_classify(results)
    _, defects = p.s6_trace(results)
    p.s7_govern(defects)
    _, tasks = p.s8_task(defects)
    _, decisions = p.s9_authorize(tasks)
    _, _manifest, ops = p.s10_repair(tasks, decisions)
    p.s11_regenerate(ops)
    ok_local = p.s12_verify_local(ops, tasks)
    ok_blast = p.s13_verify_blast(ops, tasks)
    _, clean, _drift = p.s14_reconcile()
    p.s15_seal(tasks, ok_local, ok_blast, clean)
    rec16, closed = p.s16_board_rotate(tasks, ok_local, ok_blast, clean, prev_skips)
    if closed:
        marker.write_text(canonical(
            {"cycle_id": p.cycle, "closed": True, "idempotency_key": key,
             "written_at_utc": now_utc()}) + "\n", encoding="utf-8")
        print("=== CYCLE CLOSED (16/16 staged, evidence-sealed) ===")
        return 0
    open_tasks = [t["id"] for t in rec16["details"]["task_queue"]
                  if t.get("status") != "closed"]
    print(f"=== CYCLE OPEN - {len(open_tasks)} corrective task(s): {open_tasks} ===")
    return 1 if (tasks or p.receipts["S05"]["status"] == "FAIL") else 2


def verify_chain(root: pathlib.Path) -> tuple:
    """Structural verification of the sealed receipt chain (I1, I3, I8). Read-only."""
    rev = root / "proof" / "revitalization"
    marker = rev / "CURRENT"
    if not marker.is_file():
        return 3, ["no receipt chain on disk (no cycle has ever run)"]
    try:
        current = json.loads(marker.read_text(encoding="utf-8"))
    except ValueError:
        return 1, ["CURRENT marker is not valid JSON"]
    d = rev / str(current.get("cycle_id", ""))
    if not d.is_dir():
        return 1, [f"CURRENT names missing cycle dir: {d.name}"]
    fails = []
    receipts: dict = {}
    parent = GENESIS
    for sid in STAGE_IDS:
        path = d / f"{sid}_{STAGE_NAMES[sid]}.json"
        if not path.is_file():
            later = [s for s in STAGE_IDS
                     if (d / f"{s}_{STAGE_NAMES[s]}.json").is_file()]
            fails.append(f"I1 chain gap: {sid} missing while {len(later)} later "
                         f"receipt(s) exist")
            break
        rec = read_receipt(path)
        body = {k: v for k, v in rec.items() if k != "receipt_sha256"}
        if chash(body) != rec.get("receipt_sha256"):
            fails.append(f"{sid}: receipt_sha256 mismatch (tampered or stale)")
            break
        if rec.get("parent_receipt_sha256") != parent:
            fails.append(f"I1: {sid} parent hash is not its predecessor's receipt")
            break
        if rec.get("status") not in STATES:
            fails.append(f"I3: {sid} carries illegal state {rec.get('status')!r}")
            break
        if rec.get("written_at_utc") is None:
            fails.append(f"I9: {sid} carries no timestamp")
            break
        receipts[sid] = rec
        parent = rec["receipt_sha256"]

    if not fails and len(receipts) == len(STAGE_IDS):
        s04 = receipts["S04"]["details"].get("probes", [])
        s05 = {row["probe"]: row["state"]
               for row in receipts["S05"]["details"].get("ledger", [])}
        for probe in s04:
            st = probe.get("state")
            if st == "SKIP" or probe.get("exit") == 3:
                want = "SKIP"
            elif st == "FAIL" or (probe.get("exit") is not None
                                  and probe["exit"] != 0):
                want = "FAIL"
            elif st == "INACTIVE":
                want = "INACTIVE"
            else:
                want = "PASS"
            got = s05.get(probe["probe"])
            if got and got != want:
                fails.append(f"I3: S05 says {probe['probe']}={got} but S04 measured "
                             f"exit={probe.get('exit')} state={st} "
                             f"(SKIP is never PASS)")
        for task in receipts["S08"]["details"].get("tasks", []):
            missing = [k for k in ("id", "defects", "governing_file",
                                   "baseline_commit", "acceptance_criteria",
                                   "evidence") if not task.get(k)]
            if missing:
                fails.append(f"I2: task {task.get('id')} lacks {', '.join(missing)}")
        for sid, rec in receipts.items():
            for ref in rec.get("evidence", []):
                if not (root / ref).exists():
                    fails.append(f"I8: {sid} evidence does not resolve: {ref}")
        if current.get("closed"):
            if not (d / "S15_SEAL.json").is_file():
                fails.append("I8: cycle claims closed but S15 seal is missing")
            open_tasks = [t["id"] for t
                          in receipts["S16"]["details"].get("task_queue", [])
                          if t.get("status") != "closed"]
            if open_tasks:
                fails.append(f"I8: cycle claims closed with open task(s) {open_tasks}")
            hangs = receipts["S16"]["details"].get("newly_skipped", [])
            if hangs:
                fails.append(f"I3: cycle claims closed but introduced new SKIP(s): "
                             f"{hangs}")
    return (1 if fails else 0), fails


def command_gate(root: pathlib.Path, as_json=False) -> int:
    rc, fails = verify_chain(root)
    if rc == 3:
        print("revitalization gate: SKIP (exit 3) - no receipt chain on disk yet; "
              "run `python3 tools/revitalization.py run` to create one")
        return 3
    if as_json:
        print(canonical({"gate": "revitalization", "exit": rc, "failures": fails}))
    if rc == 0:
        cur = root / "proof" / "revitalization" / "CURRENT"
        data = json.loads(cur.read_text(encoding="utf-8"))
        print(f"revitalization gate: PASS - chain {data.get('cycle_id')} is "
              f"hash-sound, serially linked, four-state legal, "
              f"{'closed+sealed' if data.get('closed') else 'open (tasks pending)'}")
        return 0
    for f in fails:
        print(f"revitalization gate: FAIL - {f}")
    return 1


def command_write_board(root: pathlib.Path) -> int:
    rc, fails = verify_chain(root)
    if rc != 0:
        for f in fails:
            print(f"revitalization write-board: REFUSED - {f}")
        return 1 if fails else 3
    rev = root / "proof" / "revitalization"
    cyc = str(json.loads((rev / "CURRENT").read_text(encoding="utf-8"))["cycle_id"])
    s16 = read_receipt(rev / cyc / "S16_BOARD+ROTATE.json")
    verdict = "closed" if s16["details"].get("closed") else "OPEN - tasks pending"
    heading = (f"## REVITALIZATION - the sixteen-stage corrective cycle "
               f"(cycle `{cyc}`, {verdict})")
    section = f"{heading}\n\n{s16['details']['board_block']}\n"
    text = BOARD.read_text(encoding="utf-8")
    if BOARD_BEGIN in text:
        pre, rest = text.split(BOARD_BEGIN, 1)
        _, post = rest.split(BOARD_END, 1)
        new_text = pre + BOARD_BEGIN + "\n" + section + "\n" + BOARD_END + post
    else:
        idx = text.find("<!-- CHAT-GATE:BEGIN")
        if idx == -1:
            new_text = (text.rstrip("\n") + "\n\n" + BOARD_BEGIN + "\n"
                        + section + "\n" + BOARD_END + "\n")
        else:
            new_text = (text[:idx] + BOARD_BEGIN + "\n" + section + "\n"
                        + BOARD_END + "\n\n" + text[idx:])
    BOARD.write_text(new_text, encoding="utf-8")
    print(f"revitalization write-board: TASKS.md updated for cycle {cyc} ({verdict})")
    return 0


