#!/usr/bin/env python3
"""omega_time.py — the Operator's clock (MUST #15, DARKITH.md §22).

Thin re-export: the single implementation is GENERATED by build/gen_synchrony.py
(build/gen/omega_time_runtime.py). Nothing here hand-writes the clock, so there is exactly
one implementation and no fork of it (NEVER #11). Zone: Asia/Manila (UTC+8).
"""
import pathlib
import sys

_GEN = pathlib.Path(__file__).resolve().parent.parent / "build" / "gen"
sys.path.insert(0, str(_GEN))
from omega_time_runtime import (  # noqa: E402,F401
    TZ, TZ_NAME, stamp, iso, log, sort_by,
)

OPERATOR_ZONE_NAME = TZ_NAME
WAKE_MARKER = pathlib.Path(__import__("os").environ.get("OMEGA_WAKE_MARKER", ".omega_wake"))


def now():
    from datetime import datetime
    return datetime.now(TZ)


def wake_anchor():
    from datetime import datetime
    if WAKE_MARKER.is_file():
        try:
            return datetime.fromisoformat(WAKE_MARKER.read_text(encoding="utf-8").strip()).astimezone(TZ)
        except ValueError:
            pass
    n = now()
    return n.replace(hour=0, minute=0, second=0, microsecond=0)


def since_wake(hours: int) -> str:
    from datetime import timedelta
    a = wake_anchor()
    return (f"anchor={stamp(a)} \u00b7 {hours}h back={stamp(now() - timedelta(hours=hours))} "
            f"(resolved from the wake marker, {TZ_NAME})")


if __name__ == "__main__":
    print(stamp())
    print(since_wake(12))
