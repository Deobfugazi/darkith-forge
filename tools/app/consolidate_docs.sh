#!/usr/bin/env bash
# consolidate_docs.sh — collapse the overlapping docs into the ONE source of truth.
# Idempotent: running it twice is a no-op. Never deletes DARKITH.md or AGENTS.md.
#
#   consolidate_docs.sh [root]           consolidate (delete the overlapping docs)
#   consolidate_docs.sh [root] --check   report only; exit 1 if consolidation is
#                                        incomplete (an OLD doc still present). CI-safe.
set -u
ROOT="${1:-/workspace/project}"
CHECK=0
for a in "$@"; do [ "$a" = "--check" ] && CHECK=1; done
[ "$CHECK" = 1 ] && [ "$ROOT" = "--check" ] && ROOT="/workspace/project"
cd "$ROOT" || exit 1

# The four overlapping docs that DARKITH.md replaces. AGENTS.md is NOT here (it is
# the live session memory; DARKITH.md is the canonical record).
OLD="singularity_progressive_continuum.md RECONCILIATION.md DEFICIT_LEDGER.md VERSION.md"
CANON="DARKITH.md"

echo "== consolidating docs =="
[ -f "$CANON" ] || { echo "DEFICIT: $CANON missing — refusing to delete anything"; exit 1; }
# guard: the canonical doc must already contain every law before we delete the sources
for L in "NEVER #11" "NEVER #15" "SPI-17" "W-042" "one surface"; do
  grep -q "$L" "$CANON" || { echo "DEFICIT: $CANON lacks '$L' — refusing to delete"; exit 1; }
done

if [ "$CHECK" = 1 ]; then
  LEFT=""
  for f in $OLD; do
    for p in "$ROOT/$f" "$ROOT/tree_omega/$f" "$ROOT/dist/$f" "$ROOT/proof/$f"; do
      [ -f "$p" ] && LEFT="$LEFT $p"
    done
  done
  if [ -n "$LEFT" ]; then
    echo "INCOMPLETE — overlapping doc(s) still present:$LEFT"
    exit 1
  fi
  echo "OK — one canonical doc ($CANON); no overlapping copies"
  exit 0
fi

# remove every copy in root, tree_omega/, and dist/ (dist copies are regenerated)
for f in $OLD; do
  for p in "$ROOT/$f" "$ROOT/tree_omega/$f" "$ROOT/dist/$f" "$ROOT/proof/$f"; do
    [ -f "$p" ] && rm -f "$p" && echo "  removed $p"
  done
done
# stray duplicates of the canonical doc elsewhere (keep only root + generated tree copy)
[ -f "$ROOT/dist/$CANON" ] && rm -f "$ROOT/dist/$CANON" && echo "  removed dist/$CANON (generated at pack time)"

# the transcript is generated by the packager; drop the hand-run copy in proof/
[ -f "$ROOT/proof/USER_PROMPTS_FULL.md" ] && rm -f "$ROOT/proof/USER_PROMPTS_FULL.md" && echo "  removed proof/USER_PROMPTS_FULL.md (generated by pack_delivery.py)"

echo "== done: one doc, one source =="
find "$ROOT" -name '*.md' -not -path '*/.git/*' -not -path '*/node_modules/*' | sort | sed 's/^/  /'
