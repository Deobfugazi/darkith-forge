#!/usr/bin/env python3
"""phantom_tree_gate.py — a gitignored duplicate source tree is not part of the repo.

Why this exists: `tree_omega/` sat in the working directory, gitignored, 15 MB, holding a
second copy of app/src. Gates that scan the working directory rather than `git ls-files`
judged that copy: the unit ledger reported a unit contradiction in a Kotlin file that does
not exist in the repository at all. The defect was invisible in git and loud in CI, which
is the worst combination — a tree that requires watching.

A phantom tree is any gitignored top-level directory that contains `app/` or `src/`. Build
outputs (build/, dist/, proof/, .tools/) are named exemptions, not phantoms: they hold
generated bytes, never a second source tree.

  python3 tools/phantom_tree_gate.py --check   # exit 1 if a phantom tree is present
  python3 tools/phantom_tree_gate.py --fix     # move it aside; never delete the operator's work

Exit: 0 = clean (or fixed); 1 = phantom present (--check); 2 = could not fix.
"""
from __future__ import annotations

import os
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Real build outputs. They are gitignored on purpose and hold generated bytes.
EXEMPT = {
    "build", "dist", "proof", ".tools", "node_modules", ".git", ".agent_tmp",
    ".forge_work", ".shell-harness", "__pycache__", "app-signed.apk", "app-signed.apk.idsig",
}


def ignored_top_dirs() -> list[str] | None:
    """None means the scan could not run. An empty list means it ran and found nothing.

    These are different facts and collapsing them is how a gate passes over nothing: git
    failing to answer is not evidence that no phantom tree exists. SPI-32 — a gate may not
    pass over zero inputs, and it may not pass over an error it treated as silence.
    """
    try:
        p = subprocess.run(
            ["git", "ls-files", "--others", "--ignored", "--exclude-standard", "--directory"],
            cwd=str(ROOT), capture_output=True, text=True, timeout=120,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if p.returncode != 0:
        return None
    out = []
    for line in p.stdout.splitlines():
        s = line.strip().rstrip("/")
        if not s or "/" in s or s in EXEMPT:
            continue
        out.append(s)
    return out


def phantoms() -> list[str] | None:
    names = ignored_top_dirs()
    if names is None:
        return None
    found = []
    for name in names:
        d = ROOT / name
        if (d / "app").is_dir() or (d / "src").is_dir():
            found.append(name)
    return found


def main(argv: list[str]) -> int:
    mode = "--fix" if "--fix" in argv else "--check"
    found = phantoms()

    if found is None:
        # Exit 3 is SKIP, never PASS: ci.sh treats it as a skip and never as green.
        print("phantom_tree_gate: SKIP — git could not enumerate ignored paths, so the scan "
              "did not run; this is not a clean tree, it is an unanswered question")
        return 3

    if not found:
        # Zero candidates is not proof of zero phantoms — nothing was examined (SPI-32). This
        # gate still fires the moment one appears, because a phantom tree is itself an ignored
        # directory and therefore a candidate. Until then it SKIPs rather than claiming a
        # clean scan it never performed.
        n = len(ignored_top_dirs() or [])
        if n == 0:
            print("phantom_tree_gate: SKIP — 0 candidate directories to scan; "
                  "nothing examined, so nothing is proven")
            return 3
        print(f"phantom_tree_gate: PASS — scanned {n} ignored director(ies); "
              f"no gitignored duplicate source tree")
        return 0

    if mode == "--check":
        print(f"phantom_tree_gate: FAIL — {len(found)} phantom source tree(s): "
              + ", ".join(found))
        print("  these are gitignored, so no reviewer sees them, but gates that scan the")
        print("  working directory judge them as if they were the repository")
        print("  remedy: python3 tools/phantom_tree_gate.py --fix")
        return 1

    moved = []
    for name in found:
        dest = pathlib.Path("/tmp") / f"{name}.phantom-{os.getpid()}"
        if dest.exists():
            shutil.rmtree(dest, ignore_errors=True)
        try:
            shutil.move(str(ROOT / name), str(dest))
            moved.append(f"{name} -> {dest}")
        except OSError as e:
            print(f"phantom_tree_gate: FAIL — could not move {name}: {e}")
            return 2
    print("phantom_tree_gate: FIXED — moved aside: " + ", ".join(moved))
    return 0 if not phantoms() else 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
